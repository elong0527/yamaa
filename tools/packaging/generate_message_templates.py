"""Generate core's message table from the condition registry (P-MSG-1).

`yaml/conditions.yaml` holds one message template per condition. This writes
the templates, sorted by condition, as the table beside the core registry
(`rust/crates/yamaa-core/src/diagnostic/message_templates.rs`) from which core
renders each issue's message. The default mode compares the committed file
with the registry, and `--write` regenerates it.
"""

import argparse

from tools.paths import ROOT
from tools.validation.repository_manifests import (
    load_condition_registry,
    message_errors,
)

TARGET = ROOT / "rust/crates/yamaa-core/src/diagnostic/message_templates.rs"


def templates() -> list[tuple[str, str]]:
    """Each registered condition and its message, sorted by condition."""
    registry, errors = load_condition_registry(ROOT)
    if errors or not isinstance(registry, dict):
        raise SystemExit("\n".join(errors) or "yaml/conditions.yaml: unreadable")
    result = []
    for condition, registration in sorted(registry["conditions"].items()):
        message = registration.get("message")
        problems = message_errors(message)
        if problems:
            raise SystemExit(
                f"yaml/conditions.yaml.conditions.{condition}.message: "
                + "; ".join(problems)
            )
        result.append((condition, message))
    return result


def literal(text: str) -> str:
    """A Rust string literal for printable ASCII text."""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render() -> str:
    lines = [
        "// Generated by tools/packaging/generate_message_templates.py --write. Do not edit.",
        "// Authoritative source: the messages of yaml/conditions.yaml.",
        "//! Each registered condition's message template, sorted by condition.",
        "#[rustfmt::skip]",
        "pub(super) const TEMPLATES: &[(&str, &str)] = &[",
    ]
    lines += [
        f"    ({literal(condition)}, {literal(message)}),"
        for condition, message in templates()
    ]
    return "\n".join([*lines, "];", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.write:
        TARGET.write_text(expected, encoding="ascii")
    else:
        assert TARGET.read_text(encoding="ascii") == expected, (
            "core's message table differs from yaml/conditions.yaml; regenerate "
            "with tools/packaging/generate_message_templates.py --write"
        )
        print("PASS: core's message table preserves the registry's messages")


if __name__ == "__main__":
    main()
