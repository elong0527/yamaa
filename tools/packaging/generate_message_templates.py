"""Generate the engine's tables of the condition registry.

`yaml/conditions.yaml` holds every condition with its phases, its message
template (P-MSG-1) and its history. This writes two tables from it:

- core's message table, each registered condition's template sorted by
  condition (`rust/crates/yamaa-core/src/diagnostic/message_templates.rs`),
  from which core renders each issue's message;
- the facade's catalogue table (`rust/crates/yamaa/src/conditions/registry.rs`),
  each registered condition's phases and the name a release renamed it from,
  then each retired condition with the release that retired it, from which
  `conditions()` builds the catalogue with the core registry's rules (#3700).

The default mode compares the committed tables with the registry, and
`--write` regenerates them.
"""

import argparse

from tools.paths import ROOT
from tools.validation.repository_manifests import (
    load_condition_registry,
    message_errors,
    registry_errors,
)

TARGET = ROOT / "rust/crates/yamaa-core/src/diagnostic/message_templates.rs"
CATALOGUE = ROOT / "rust/crates/yamaa/src/conditions/registry.rs"


def registry() -> dict:
    """The condition registry, refused when it is unreadable or its form is
    wrong, as the repository validator reports it."""
    document, errors = load_condition_registry(ROOT)
    if errors or not isinstance(document, dict):
        raise SystemExit("\n".join(errors) or "yaml/conditions.yaml: unreadable")
    problems = registry_errors(document)
    if problems:
        raise SystemExit("\n".join(problems))
    return document


def templates(document=None) -> list[tuple[str, str]]:
    """Each registered condition and its message, sorted by condition."""
    result = []
    for condition, registration in sorted(
        (document or registry())["conditions"].items()
    ):
        message = registration.get("message")
        problems = message_errors(message)
        if problems:
            raise SystemExit(
                f"yaml/conditions.yaml.conditions.{condition}.message: "
                + "; ".join(problems)
            )
        result.append((condition, message))
    return result


def registered(document=None) -> list[tuple[str, list[str], str | None]]:
    """Each registered condition, its phases and the name a release renamed
    it from, or None, sorted by condition."""
    return [
        (condition, registration["phases"], registration.get("renamed_from"))
        for condition, registration in sorted(
            (document or registry())["conditions"].items()
        )
    ]


def retired(document=None) -> list[tuple[str, str]]:
    """Each retired condition and the release that retired it, sorted."""
    return [
        (condition, entry["retired_in"])
        for condition, entry in sorted(
            (document or registry()).get("retired", {}).items()
        )
    ]


def literal(text: str) -> str:
    """A Rust string literal for printable ASCII text."""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(document=None) -> str:
    lines = [
        "// Generated by tools/packaging/generate_message_templates.py --write. Do not edit.",
        "// Authoritative source: the messages of yaml/conditions.yaml.",
        "//! Each registered condition's message template, sorted by condition.",
        "#[rustfmt::skip]",
        "pub(super) const TEMPLATES: &[(&str, &str)] = &[",
    ]
    lines += [
        f"    ({literal(condition)}, {literal(message)}),"
        for condition, message in templates(document)
    ]
    lines += [
        "];",
        "",
        "#[rustfmt::skip]",
        "pub(super) const VARIANTS: &[(&str, &str, &str)] = &[",
    ]
    for condition, entry in sorted((document or registry())["conditions"].items()):
        for variant in entry.get("message_variants", []):
            lines.append(
                f"    ({literal(condition)}, {literal(variant['when'])}, {literal(variant['message'])}),"
            )
    return "\n".join([*lines, "];", ""])


def render_catalogue(document=None) -> str:
    def former(name):
        return "None" if name is None else f"Some({literal(name)})"

    lines = [
        "// Generated by tools/packaging/generate_message_templates.py --write. Do not edit.",
        "// Authoritative source: yaml/conditions.yaml.",
        "//! The registry as the catalogue bundles it: each registered condition",
        "//! with its phases and the name a release renamed it from, then each",
        "//! retired condition with the release that retired it, each sorted by",
        "//! condition.",
        "#[rustfmt::skip]",
        "pub(super) const REGISTERED: &[(&str, &[&str], Option<&str>)] = &[",
    ]
    lines += [
        f"    ({literal(condition)}, &[{', '.join(map(literal, phases))}], "
        f"{former(renamed_from)}),"
        for condition, phases, renamed_from in registered(document)
    ]
    lines += [
        "];",
        "#[rustfmt::skip]",
        "pub(super) const RETIRED: &[(&str, &str)] = &[",
    ]
    lines += [
        f"    ({literal(condition)}, {literal(release)}),"
        for condition, release in retired(document)
    ]
    return "\n".join([*lines, "];", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    document = registry()
    expected = {TARGET: render(document), CATALOGUE: render_catalogue(document)}
    if args.write:
        for target, text in expected.items():
            target.write_text(text, encoding="ascii")
    else:
        for target, text in expected.items():
            assert target.read_text(encoding="ascii") == text, (
                f"{target.relative_to(ROOT)} differs from yaml/conditions.yaml; "
                "regenerate with tools/packaging/generate_message_templates.py --write"
            )
        print(
            "PASS: core's message table and the facade's catalogue table preserve "
            "the registry"
        )


if __name__ == "__main__":
    main()
