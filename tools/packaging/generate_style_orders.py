"""Generate the lint's field orders from the authoritative schema fields.

`field_order` orders the root of a specification, each input dataset, the
output, each named intermediate, each column and each row template by the
fields their schema classes declare. This writes those orders, with every
`fields_from` reference expanded, as constants of the Rust lint
(`rust/crates/yamaa-adapters/src/lint/fields.rs`); the default mode compares
the committed file with the schemas and `--write` regenerates it.
"""

import argparse

import yaml
from tools.paths import ROOT

TARGET = ROOT / "rust/crates/yamaa-adapters/src/lint/fields.rs"
CLASSES = (
    "root_class",
    "dataset_class",
    "output_class",
    "intermediate_class",
    "column_class",
    "row_class",
)


def orders():
    """Each ordered class's field names, `fields_from` references expanded."""
    classes = {}
    for source in sorted((ROOT / "yaml").glob("schema*.yaml")):
        if source.name in {"schema_environment.yaml", "schema_project.yaml"}:
            continue
        classes.update(
            (name, value)
            for name, value in yaml.safe_load(source.read_text()).items()
            if isinstance(value, list) and name.endswith(("_class", "_fields"))
        )

    def fields(name, stack=()):
        if name in stack:
            raise ValueError("cyclic fields_from in style order")
        result = []
        for entry in classes[name]:
            if "fields_from" in entry:
                result.extend(fields(entry["fields_from"], (*stack, name)))
            else:
                result.extend(entry)
        return tuple(result)

    return {name: fields(name) for name in CLASSES}


def render():
    lines = [
        "// Generated by tools/packaging/generate_style_orders.py --write. Do not edit.",
        "// Authoritative sources: the class field lists of yaml/schema*.yaml.",
        "//! The schema field order `field_order` checks, one constant per class.",
    ]
    for name, fields in orders().items():
        values = ", ".join(f'"{field}"' for field in fields)
        lines += [
            "#[rustfmt::skip]",
            f"pub(super) const {name.upper()}: &[&str] = &[{values}];",
        ]
    return "\n".join([*lines, ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.write:
        TARGET.write_text(expected)
    else:
        assert TARGET.read_text() == expected, (
            "the lint's field orders differ from the schemas; regenerate with "
            "tools/packaging/generate_style_orders.py --write"
        )
        print("PASS: the lint's field orders preserve schema field order")


if __name__ == "__main__":
    main()
