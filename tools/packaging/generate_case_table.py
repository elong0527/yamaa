"""Generate the case table behind the engine's ordinal case-insensitive
comparison of locations (OUTPUT-9, D396) from pinned Unicode data.

`file_resources::equal_ignoring_case` compares two locations by the simple
uppercase of each UTF-16 code unit, as Windows' ordinal comparison does, or of
each Unicode scalar, as on macOS. The mapping is data,
`rust/crates/yamaa-adapters/casing/uppercase.txt`, read with `include_str!`,
so the comparison does not change with the compiler's Unicode tables. Each line
maps one code point to its simple uppercase (field 12 of `UnicodeData.txt`),
leaving out the code points in `UNMAPPED`, which Windows' ordinal comparison
does not map. Every unlisted code point, and a surrogate code unit, maps to
itself.

The source is `SOURCE`: fields 0 and 12 of `UnicodeData.txt` of Unicode
`VERSION`, for the rows that state a simple uppercase, cut from the published
file (`PUBLISHED`) with `--cut`. Unicode 15.0.0 is pinned as the version
closest to Windows' ordinal table: Unicode 16.0 to 18.0 added the BMP case
pairs of U+019B, U+0264, U+0277, U+027C, U+1C8A, U+A7CD, U+A7CF, U+A7D3,
U+A7D5, U+A7DB, U+AB4B and U+AB4C, letters that Windows' table, which predates
them, does not map. The Windows oracle test in `file_resources.rs` compares the
table with `CompareStringOrdinal` on the native run, which settles the choice.

The default mode rebuilds the table from `SOURCE` and compares it, and the
Unicode notice beside the source, byte for byte; `--write` regenerates them.
Neither fetches anything.
"""

import argparse
import sys

from tools.paths import ROOT

ADAPTERS = ROOT / "rust/crates/yamaa-adapters"
TARGET = ADAPTERS / "casing/uppercase.txt"
VERSION = "15.0.0"
SOURCE = ADAPTERS / f"unicode/{VERSION}/UnicodeData-uppercase.txt"
PUBLISHED = f"https://www.unicode.org/Public/{VERSION}/ucd/UnicodeData.txt"
# The Unicode notice beside the source, kept byte for byte with yamaa-core's.
LICENSE = ADAPTERS / "unicode/LICENSE.txt"
CORE_LICENSE = ROOT / "rust/crates/yamaa-core/unicode/LICENSE.txt"
# Lowercase letters whose simple uppercase Windows' ordinal comparison leaves
# unmapped: the dotless i and the long s.
UNMAPPED = (0x0131, 0x017F)
SOURCE_HEADER = (
    f"# Fields 0 and 12 of UnicodeData.txt of Unicode {VERSION}\n"
    f"# ({PUBLISHED}): each code point that states\n"
    f"# a simple uppercase mapping, and that mapping. Cut by\n"
    f"# tools/packaging/generate_case_table.py --cut. See ../LICENSE.txt.\n"
)
HEADER = (
    f"# The simple uppercase of each code point, from\n"
    f"# UnicodeData.txt of Unicode {VERSION} ({PUBLISHED}),\n"
    f"# without {', '.join(f'U+{unit:04X}' for unit in UNMAPPED)}. "
    f"Generated by tools/packaging/generate_case_table.py.\n"
    f"# Each line: a code point and its uppercase, in hex.\n"
)


def cut(published):
    """The source text: fields 0 and 12 of the published `UnicodeData.txt`
    text, for each row that states a simple uppercase."""
    rows = []
    for line in published.splitlines():
        fields = line.split(";")
        if fields[12]:
            rows.append(f"{fields[0]};{fields[12]}\n")
    return SOURCE_HEADER + "".join(rows)


def table(source):
    """The `(code point, uppercase)` pairs the source text states, without
    `UNMAPPED`, ascending."""
    if not source.startswith(SOURCE_HEADER):
        raise ValueError(f"{SOURCE.relative_to(ROOT)} does not start with its header")
    pairs = []
    for line in source[len(SOURCE_HEADER) :].splitlines():
        unit, upper = (int(field, 16) for field in line.split(";"))
        if unit not in UNMAPPED and upper != unit:
            pairs.append((unit, upper))
    return sorted(pairs)


def render(pairs):
    """The table file of `pairs`."""
    return HEADER + "".join(f"{unit:04X} {upper:04X}\n" for unit, upper in pairs)


def expected():
    """Each generated file and the bytes it must hold."""
    source = SOURCE.read_text(encoding="ascii")
    return {
        TARGET: render(table(source)).encode("ascii"),
        LICENSE: CORE_LICENSE.read_bytes(),
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write", action="store_true")
    group.add_argument(
        "--cut", metavar="UnicodeData.txt", help=f"re-cut SOURCE from {PUBLISHED}"
    )
    arguments = parser.parse_args(argv)
    if arguments.cut:
        with open(arguments.cut, encoding="utf-8") as published:
            SOURCE.parent.mkdir(parents=True, exist_ok=True)
            SOURCE.write_text(cut(published.read()), encoding="ascii", newline="\n")
        arguments.write = True
    files = expected()
    if arguments.write:
        for path, content in files.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
        return 0
    stale = [path for path, content in files.items() if path.read_bytes() != content]
    for path in stale:
        print(
            f"{path.relative_to(ROOT) if path.is_relative_to(ROOT) else path} "
            f"differs from Unicode {VERSION}: run "
            "python -m tools.packaging.generate_case_table --write",
            file=sys.stderr,
        )
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
