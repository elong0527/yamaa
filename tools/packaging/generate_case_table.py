"""Generate the case table behind the engine's ordinal case-insensitive
comparison of locations (OUTPUT-9, D396).

`file_resources::equal_ignoring_case` compares two locations as Windows'
ordinal comparison does: each UTF-16 code unit by its simple uppercase. The
mapping is data, `rust/crates/yamaa-adapters/casing/uppercase.txt`, read with
`include_str!`, so the comparison does not change with the compiler's Unicode
tables. Each line maps one Basic Multilingual Plane code point to its simple
uppercase (field 12 of `UnicodeData.txt`) at the version `VERSION` names,
leaving out the code points in `UNMAPPED`, which Windows' ordinal comparison
does not map. A surrogate and every unlisted code unit map to themselves.

The default mode checks the committed file's form: its header, and lines of
two distinct four-digit hex code points, ascending, outside the surrogates
and `UNMAPPED`. With `--source UnicodeData.txt` of `VERSION` it also compares
the file with the table generated from it, and `--write` regenerates the file.
The source is not fetched here; it is published at `SOURCE`.
"""

import argparse
import re
import sys

from tools.paths import ROOT

TARGET = ROOT / "rust/crates/yamaa-adapters/casing/uppercase.txt"
VERSION = "15.0.0"
SOURCE = f"https://www.unicode.org/Public/{VERSION}/ucd/UnicodeData.txt"
# Lowercase letters whose simple uppercase Windows' ordinal comparison leaves
# unmapped: the dotless i and the long s.
UNMAPPED = (0x0131, 0x017F)
HEADER = (
    f"# The simple uppercase of each Basic Multilingual Plane code point, from\n"
    f"# UnicodeData.txt of Unicode {VERSION} ({SOURCE}),\n"
    f"# without {', '.join(f'U+{unit:04X}' for unit in UNMAPPED)}. "
    f"Generated by tools/packaging/generate_case_table.py.\n"
    f"# Each line: a code unit and its uppercase, in hex.\n"
)
LINE = re.compile(r"([0-9A-F]{4}) ([0-9A-F]{4})")


def table(source):
    """The `(code point, uppercase)` pairs `UnicodeData.txt` text states."""
    pairs = []
    for line in source.splitlines():
        fields = line.split(";")
        unit, upper = int(fields[0], 16), fields[12]
        if unit > 0xFFFF or not upper or unit in UNMAPPED:
            continue
        upper = int(upper, 16)
        if upper <= 0xFFFF and upper != unit:
            pairs.append((unit, upper))
    return sorted(pairs)


def render(pairs):
    return HEADER + "".join(f"{unit:04X} {upper:04X}\n" for unit, upper in pairs)


def problems(text):
    """What makes `text` not a case table of this form."""
    if not text.startswith(HEADER):
        return ["the header does not name this generator's version and exclusions"]
    found, previous = [], -1
    for number, line in enumerate(text[len(HEADER) :].splitlines(), 1):
        match = LINE.fullmatch(line)
        if not match:
            found.append(f"line {number}: not two four-digit hex code points")
            continue
        unit, upper = (int(group, 16) for group in match.groups())
        if unit <= previous:
            found.append(f"line {number}: U+{unit:04X} is not ascending")
        if unit == upper or unit in UNMAPPED:
            found.append(f"line {number}: U+{unit:04X} maps where it may not")
        if any(0xD800 <= point <= 0xDFFF for point in (unit, upper)):
            found.append(f"line {number}: a surrogate is mapped")
        previous = unit
    return found


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", help=f"UnicodeData.txt of Unicode {VERSION}")
    parser.add_argument("--write", action="store_true")
    arguments = parser.parse_args(argv)
    if arguments.write:
        if not arguments.source:
            parser.error("--write needs --source")
        with open(arguments.source, encoding="utf-8") as source:
            TARGET.write_text(render(table(source.read())), encoding="utf-8")
        return 0
    text = TARGET.read_text(encoding="utf-8")
    found = problems(text)
    if arguments.source:
        with open(arguments.source, encoding="utf-8") as source:
            if render(table(source.read())) != text:
                found.append("the table differs from the one the source generates")
    for problem in found:
        print(f"{TARGET.relative_to(ROOT)}: {problem}", file=sys.stderr)
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main())
