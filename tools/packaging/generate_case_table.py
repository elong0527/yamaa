"""Generate the case table behind the engine's ordinal case-insensitive
comparison of locations (OUTPUT-9, D396) from pinned Unicode data.

`file_resources::equal_ignoring_case` compares two locations by the simple
uppercase of each UTF-16 code unit, as Windows' ordinal comparison does, less
the rows Windows does not apply, or of each Unicode scalar, as on macOS. The mapping is data,
`rust/crates/yamaa-adapters/casing/uppercase.txt`, read with `include_str!`,
so the comparison does not change with the compiler's Unicode tables. Each line
maps one code point to its simple uppercase (field 12 of `UnicodeData.txt`),
leaving out the code points in `UNMAPPED`, which Windows' ordinal comparison
does not map. Every unlisted code point, and a surrogate code unit, maps to
itself.

The source is `SOURCE`: fields 0 and 12 of `UnicodeData.txt` of Unicode
`VERSION`, for the rows that state a simple uppercase, cut from the published
file (`PUBLISHED`) with `--cut`. The table is the pinned Unicode cut that the
macOS policy reads whole (D396); Unicode 16.0 to 18.0 added BMP case pairs
(U+019B, U+0264, U+0277, U+027C, U+1C8A, U+A7CD, U+A7CF, U+A7D3, U+A7D5,
U+A7DB, U+AB4B and U+AB4C) that Windows' ordinal table does not map either.

Windows' ordinal table is not a Unicode version: `CompareStringOrdinal`
applies only some of the table's BMP rows (#4991). The Windows policy leaves
out the rows of the code units in `WINDOWS_TARGET`, which this generator
derives from `RECORD`, what the Windows oracle test in `file_resources.rs`
printed on windows-2025 against the table alone. Each recorded line names two
of Windows' classes that share one table uppercase; every code unit of a class
that does not hold that uppercase has a row Windows does not apply. A class of
three or more units under one uppercase is recorded pairwise (U+0422/U+0442
from U+1C84, U+1C84 from U+1C85), and each line excepts the units of each of
its classes that lacks the uppercase, so U+1C84 and U+1C85 are both excepted
and U+0442 is kept. The derivation refuses a line whose classes do not share
one table uppercase, and a "Windows joins" line, which only a table row can
answer.

The default mode rebuilds the table and the Windows exceptions from `SOURCE`
and `RECORD` and compares them, and the Unicode notice beside the source, byte
for byte; `--write` regenerates them. Neither fetches anything.
"""

import argparse
import re
import sys

from tools.packaging import generated
from tools.paths import ROOT

ADAPTERS = ROOT / "rust/crates/yamaa-adapters"
TARGET = ADAPTERS / "casing/uppercase.txt"
VERSION = "15.0.0"
SOURCE = ADAPTERS / f"unicode/{VERSION}/UnicodeData-uppercase.txt"
PUBLISHED = f"https://www.unicode.org/Public/{VERSION}/ucd/UnicodeData.txt"
# The Unicode notice beside the source, kept byte for byte with yamaa-core's.
LICENSE = ADAPTERS / "unicode/LICENSE.txt"
CORE_LICENSE = ROOT / "rust/crates/yamaa-core/unicode/LICENSE.txt"
# The Windows oracle test's output against the table alone (#4991), and the
# code units whose table row the Windows policy does not apply, derived from it.
RECORD = ADAPTERS / "tests/fixtures/windows_ordinal_separations.txt"
WINDOWS_TARGET = ADAPTERS / "casing/windows-unmapped.txt"
SEPARATES = re.compile(r"Windows separates (\S+) from (\S+)")
# Lowercase letters whose simple uppercase Windows' ordinal comparison leaves
# unmapped: the dotless i and the long s.
UNMAPPED = (0x0131, 0x017F)
SOURCE_HEADER = (
    f"# Fields 0 and 12 of UnicodeData.txt of Unicode {VERSION}\n"
    f"# ({PUBLISHED}): each code point that states\n"
    f"# a simple uppercase mapping, and that mapping. Cut by\n"
    f"# tools/packaging/generate_case_table.py --cut. See ../LICENSE.txt.\n"
)
HEADER = (
    f"# The simple uppercase of each code point, from\n"
    f"# UnicodeData.txt of Unicode {VERSION} ({PUBLISHED}),\n"
    f"# without {', '.join(f'U+{unit:04X}' for unit in UNMAPPED)}. "
    f"Generated by tools/packaging/generate_case_table.py.\n"
    f"# Each line: a code point and its uppercase, in hex.\n"
)
WINDOWS_HEADER = (
    "# The UTF-16 code units whose row of uppercase.txt Windows' ordinal\n"
    "# comparison does not apply, so the Windows policy maps each to itself.\n"
    "# Derived from the Windows oracle test's output on windows-2025 (#4991),\n"
    "# tests/fixtures/windows_ordinal_separations.txt, by\n"
    "# tools/packaging/generate_case_table.py. Each line: a code unit, in hex.\n"
)


def cut(published):
    """The source text: fields 0 and 12 of the published `UnicodeData.txt`
    text, for each row that states a simple uppercase."""
    rows = []
    for line in published.splitlines():
        fields = line.split(";")
        if fields[12]:
            rows.append(f"{fields[0]};{fields[12]}\n")
    return SOURCE_HEADER + "".join(rows)


def table(source):
    """The `(code point, uppercase)` pairs the source text states, without
    `UNMAPPED`, ascending."""
    if not source.startswith(SOURCE_HEADER):
        raise ValueError(f"{SOURCE.relative_to(ROOT)} does not start with its header")
    pairs = []
    for line in source[len(SOURCE_HEADER) :].splitlines():
        unit, upper = (int(field, 16) for field in line.split(";"))
        if unit not in UNMAPPED and upper != unit:
            pairs.append((unit, upper))
    return sorted(pairs)


def windows_unmapped(pairs, record):
    """The code units whose row of `pairs` Windows' ordinal comparison does
    not apply, ascending, derived from the oracle's `record` text."""
    upper = dict(pairs)
    units = set()
    for line in record.splitlines():
        if line.startswith("#"):
            continue
        match = SEPARATES.fullmatch(line)
        if not match:
            raise ValueError(f"{RECORD.name}: {line!r} is not a separation")
        classes = [
            [int(unit.removeprefix("U+"), 16) for unit in group.split("/")]
            for group in match.groups()
        ]
        uppers = {upper.get(unit, unit) for group in classes for unit in group}
        if len(uppers) != 1:
            raise ValueError(
                f"{RECORD.name}: {line!r} spans uppercases {sorted(uppers)}"
            )
        (shared,) = uppers
        for group in classes:
            if shared not in group:
                units.update(group)
    return sorted(units)


def render_windows(units):
    """The Windows exceptions file of `units`."""
    return WINDOWS_HEADER + "".join(f"{unit:04X}\n" for unit in units)


def render(pairs):
    """The table file of `pairs`."""
    return HEADER + "".join(f"{unit:04X} {upper:04X}\n" for unit, upper in pairs)


def expected():
    """Each generated file and the bytes it must hold."""
    pairs = table(SOURCE.read_text(encoding="ascii"))
    record = RECORD.read_text(encoding="ascii")
    return {
        TARGET: render(pairs).encode("ascii"),
        WINDOWS_TARGET: render_windows(windows_unmapped(pairs, record)).encode("ascii"),
        LICENSE: CORE_LICENSE.read_bytes(),
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write", action="store_true")
    group.add_argument(
        "--cut", metavar="UnicodeData.txt", help=f"re-cut SOURCE from {PUBLISHED}"
    )
    arguments = parser.parse_args(argv)
    if arguments.cut:
        with open(arguments.cut, encoding="utf-8") as published:
            SOURCE.parent.mkdir(parents=True, exist_ok=True)
            SOURCE.write_text(cut(published.read()), encoding="ascii", newline="\n")
        arguments.write = True
    return generated.sync(
        expected(),
        write=arguments.write,
        command="tools.packaging.generate_case_table",
        passed=f"the case tables are Unicode {VERSION}'s and the Windows record's",
    )


if __name__ == "__main__":
    sys.exit(main())
