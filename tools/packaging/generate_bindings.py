def _stub_def(name, args, returns, indent):
    """Render one stub definition the way ruff format lays it out (88 cols)."""
    single = f"{indent}def {name}({args}) -> {returns}: ..."
    if len(single) <= 88:
        return [single]
    inner = indent + "    "
    if len(f"{inner}{args}") <= 88:
        return [
            f"{indent}def {name}(",
            f"{inner}{args}",
            f"{indent}) -> {returns}: ...",
        ]
    lines = [f"{indent}def {name}("]
    lines += [f"{inner}{part}," for part in bindings_public._split_rendered_args(args)]
    lines.append(f"{indent}) -> {returns}: ...")
    return lines


def _render_pyi(definition):
    classes = {
        export["name"]
        for export in definition["python"]["exports"]
        if export["kind"] == "class"
    }
    items = []
    for export in definition["python"]["exports"]:
        kind = export["kind"]
        name = export["name"]
        if kind == "constant":
            rendered = _python_type(_type_node(export["type"]), definition, classes)
            items.append((kind, f"{name}: {rendered}"))
        elif kind == "exception":
            error = definition["public"]["errors"]["refusal"]["python"]
            if name == error["native"]:
                attributes = error["attributes"]
                lines = [f"class {name}({export['base']}):"]
                lines += [
                    f"    {key}: {bindings_public._PY_ANNOTATION[token]}"
                    for key, token in attributes.items()
                ]
                args = ", ".join(
                    ["self", "message: str"]
                    + [
                        f"{key}: {bindings_public._PY_ANNOTATION[token]}"
                        for key, token in attributes.items()
                    ]
                )
                lines += _stub_def("__init__", args, "None", "    ")
                lines += _stub_def("__reduce__", "self", "tuple", "    ")
                items.append((kind, "\n".join(lines)))
            else:
                items.append((kind, f"class {name}({export['base']}): ..."))
        elif kind == "function":
            args = _python_args(export.get("args"), definition, classes)
            returns = _python_type(_type_node(export["returns"]), definition, classes)
            items.append((kind, "\n".join(_stub_def(name, args, returns, ""))))
        elif kind == "class" and not export.get("methods"):
            # An opaque handle without methods still needs a stub body.
            items.append((kind, f"class {name}: ..."))
        elif kind == "class":
            lines = [f"class {name}:"]
            for method in export.get("methods", []):
                args = _python_args(method.get("args"), definition, classes)
                returns = _python_type(
                    _type_node(method["returns"]), definition, classes
                )
                prefix = ", " if args else ""
                if method.get("kind") == "getter":
                    lines.append("    @property")
                lines.extend(
                    _stub_def(method["name"], f"self{prefix}{args}", returns, "    ")
                )
            items.append((kind, "\n".join(lines)))
    # Stub style (ruff format): one blank line between top-level items,
    # except that consecutive function definitions stay adjacent.
    body = items[0][1]
    for (previous, _), (kind, text) in zip(items, items[1:]):
        body += ("\n" if previous == kind == "function" else "\n\n") + text
    return "\n".join([*_PYI_HEADER, "", body, ""])


def _registration(export):
    kind = export["kind"]
    name = export["name"]
    rust = export["rust"]
    if kind == "constant":
        if rust != "yamaa_core::VERSION":
            raise ValueError(f"unsupported constant source for {name}: {rust}")
        return ['    module.add("_CORE_VERSION", env!("CARGO_PKG_VERSION"))?;']
    if kind == "class":
        return [f"    module.add_class::<{rust}>()?;"]
    if kind == "exception":
        arguments = f'"{name}", module.py().get_type::<{rust}>()'
        single = f"    module.add({arguments})?;"
        # rustfmt keeps a call on one line when its arguments fit the default
        # fn_call_width (60) and the line fits max_width (100).
        if len(arguments) <= 60 and len(single) <= 100:
            return [single]
        return [
            "    module.add(",
            f'        "{name}",',
            f"        module.py().get_type::<{rust}>(),",
            "    )?;",
        ]
    if kind == "function":
        single = f"    module.add_function(wrap_pyfunction!({rust}, module)?)?;"
        if len(single) < 100:
            return [single]
        return [
            "    module.add_function(wrap_pyfunction!(",
            f"        {rust},",
            "        module",
            "    )?)?;",
        ]
    raise ValueError(f"unsupported Python export kind: {kind!r}")


def _render_lib_rs(definition):
    src = RUST_TARGET.parent
    modules = sorted(path.stem for path in src.glob("*.rs") if path.name != "lib.rs")
    if not modules:
        raise ValueError("yamaa-python has no implementation modules")
    lines = [
        *_RUST_HEADER,
        "//! Python composition roots and lossless public result conversion.",
        "use pyo3::prelude::*;",
        *(f"mod {module};" for module in modules),
        "#[pymodule]",
        "fn _native(module: &Bound<'_, PyModule>) -> PyResult<()> {",
    ]
    for export in definition["python"]["exports"]:
        lines.extend(_registration(export))
    lines += ["    Ok(())", "}", ""]
    return "\n".join(lines)


def render_manifest(definition, public):
    """The normalized manifest: every frozen element, one per line."""
    lines = bindings_surface.manifest_lines(definition) + public.manifest_lines()
    return "\n".join([*_MANIFEST_HEADER, *lines, ""])


def _check_gate(definition):
    """Every registered native function of each binding reaches the gate,
    apart from the handshake and the R core version, the R function of an
    operation whose Python side is only the informational version constant."""
    handshake = definition["handshake"]
    constants = {
        export["name"]
        for export in definition["python"]["exports"]
        if export["kind"] == "constant"
    }
    informational = {
        name
        for hosts in definition["operations"].values()
        if hosts.get("python") and set(hosts["python"]) <= constants
        for name in hosts.get("r", [])
    }
    python = [
        export["rust"].rpartition("::")[2]
        for export in definition["python"]["exports"]
        if export["kind"] == "function"
    ]
    r = [
        function["name"]
        for group in definition["r"]["groups"]
        for function in group["functions"]
    ]
    for host, registered, exempt, source in (
        ("python", python, {handshake["python"]}, RUST_TARGET.parent),
        ("r", r, {handshake["r"], *informational}, R_SOURCE),
    ):
        paths = sorted(source.glob("*.rs"))
        functions = bindings_handshake.free_functions(paths, _strip_rust, _block)
        bindings_handshake.check_gate(host, registered, exempt, functions)


def render_all():
    definition = _load_definition()
    _reconcile(definition)
    _reconcile_r(definition)
    _check_gate(definition)
    public = bindings_public.Public(definition)
    rendered = {
        PYI_TARGET: _render_pyi(definition),
        RUST_TARGET: _render_lib_rs(definition),
        PUBLIC_PYTHON_TARGET: public.render_python(
            _PYI_HEADER, bindings_handshake.python_lines(definition)
        ),
        R_WRAPPERS_TARGET: _render_r_wrappers(definition),
        PUBLIC_R_TARGET: public.render_r(_PYI_HEADER),
        NAMESPACE_TARGET: public.render_namespace(_PYI_HEADER),
        MANIFEST_TARGET: render_manifest(definition, public),
    }
    for group in definition["r"]["groups"]:
        target = R_SOURCE / "generated" / f"{group['module']}.rs"
        rendered[target] = _render_r_registration(group, definition["r"])
    return rendered


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args(argv)
    rendered = render_all()
    for target, text in rendered.items():
        expected = text.encode("utf-8")
        if args.write:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(expected)
        else:
            assert target.read_bytes() == expected, (
                f"{target.relative_to(ROOT)} differs from "
                "rust/interface/bindings.yaml; regenerate with "
                "tools/packaging/generate_bindings.py --write"
            )
            print(
                f"PASS: {target.relative_to(ROOT)} matches rust/interface/bindings.yaml"
            )


if __name__ == "__main__":
    main()
