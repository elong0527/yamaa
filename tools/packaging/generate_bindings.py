# --- Definition loading: closed YAML grammar ---------------------------------


def _plain(node, seen=None):
    """Convert a YAML node tree to plain values, rejecting non-plain input."""
    if seen is None:
        seen = set()
    if id(node) in seen:
        # PyYAML's composer hands back the anchored node itself for an
        # alias, so a node object appearing twice is an alias reference.
        raise ValueError("bindings.yaml must not use YAML aliases")
    seen.add(id(node))
    if not node.tag.startswith("tag:yaml.org,2002:"):
        raise ValueError(f"bindings.yaml uses a non-standard tag: {node.tag}")
    if isinstance(node, yaml.MappingNode):
        result = {}
        for key_node, value_node in node.value:
            key = _plain(key_node, seen)
            if not isinstance(key, (str, int)) or isinstance(key, bool):
                raise ValueError("bindings.yaml mapping keys must be text")
            if key in result:
                raise ValueError(f"duplicate key in bindings.yaml: {key}")
            result[key] = _plain(value_node, seen)
        return result
    if isinstance(node, yaml.SequenceNode):
        return [_plain(child, seen) for child in node.value]
    if isinstance(node, yaml.ScalarNode):
        if node.tag == "tag:yaml.org,2002:str":
            return node.value
        if node.tag == "tag:yaml.org,2002:int":
            return int(node.value)
        if node.tag == "tag:yaml.org,2002:bool":
            return node.value in ("true", "True")
        if node.tag == "tag:yaml.org,2002:null":
            return None
    raise ValueError(f"unsupported YAML node in bindings.yaml: {node.tag}")


def _text_keys(value, path=()):
    """Refuse non-text mapping keys, apart from the CLI's exit statuses."""
    if isinstance(value, dict):
        for key, item in value.items():
            if not isinstance(key, str) and path != ("cli", "exit_status"):
                raise ValueError(f"bindings.yaml mapping keys must be text: {key!r}")
            _text_keys(item, (*path, str(key)))
    elif isinstance(value, list):
        for item in value:
            _text_keys(item, path)


def _load_definition():
    with DEFINITION.open(encoding="utf-8") as stream:
        node = yaml.compose(stream)
    if node is None:
        raise ValueError("bindings.yaml is empty")
    definition = _plain(node)
    if not isinstance(definition, dict):
        raise ValueError("bindings.yaml must be a mapping")
    _text_keys(definition)
    unknown = set(definition) - _TOP_LEVEL_KEYS
    if unknown:
        raise ValueError(f"unknown top-level keys in bindings.yaml: {sorted(unknown)}")
    missing = _TOP_LEVEL_KEYS - set(definition)
    if missing:
        raise ValueError(f"missing top-level keys in bindings.yaml: {sorted(missing)}")
    if definition["format"] != "yamaa.host-interface":
        raise ValueError(f"unexpected interface format: {definition['format']!r}")
    if definition["format_version"] != 2:
        raise ValueError(
            f"unsupported interface format_version: {definition['format_version']!r}"
        )
    if definition["boundary"] != "rust_generated_host_glue":
        raise ValueError(f"unexpected boundary: {definition['boundary']!r}")
    if definition["contract"] != "README.md":
        raise ValueError(f"unexpected contract document: {definition['contract']!r}")
    _resolve_imports(definition)
    _validate_python(definition)
    _validate_r(definition)
    bindings_surface.validate_values(definition["values"])
    bindings_surface.validate_tables(definition["tables"], definition["values"])
    bindings_surface.validate_records(definition["records"], definition["values"])
    bindings_surface.validate_cli(
        definition["cli"], definition["values"], definition["operations"]
    )
    _validate_operations(definition)
    bindings_handshake.validate(definition)
    bindings_public.Public(definition)
    return definition


def _resolve_imports(definition):
    for name, (crate, roles) in _IMPORT_ROLES.items():
        entry = definition["imports"].get(name)
        if not isinstance(entry, dict):
            raise ValueError(f"bindings.yaml is missing the {name} import")
        if entry.get("crate") != crate:
            raise ValueError(f"the {name} import must name the {crate} crate")
        if not isinstance(entry.get("roles"), list) or set(entry["roles"]) != set(
            roles
        ):
            raise ValueError(f"{name} roles must be exactly {sorted(roles)}")
        for role in entry["roles"]:
            path, symbol = roles[role]
            source = path.read_text(encoding="utf-8")
            pattern = rf"pub (?:const|struct) {symbol}\b"
            if not re.search(pattern, source):
                raise ValueError(
                    f"{name} role {role} does not resolve to {symbol} "
                    f"in {path.relative_to(WORKSPACE).as_posix()}"
                )


def _validate_python(definition):
    python = definition["python"]
    unknown = set(python) - {"module", "registration", "exports"}
    if unknown:
        raise ValueError(f"unknown Python definition keys: {sorted(unknown)}")
    if python.get("module") != "yamaa._native":
        raise ValueError(f"unexpected Python module: {python.get('module')!r}")
    if python.get("registration") != "rust/crates/yamaa-python/src/lib.rs":
        raise ValueError("unexpected Python registration path")
    names = []
    for export in python["exports"]:
        kind = export.get("kind")
        if kind not in ("constant", "class", "exception", "function"):
            raise ValueError(f"unsupported Python export kind: {kind!r}")
        name = export.get("name")
        if not isinstance(name, str) or not _NAME.fullmatch(name):
            raise ValueError(f"invalid Python export name: {name!r}")
        names.append(name)
        rust = export.get("rust")
        if not isinstance(rust, str) or not all(
            _NAME.fullmatch(part) for part in rust.split("::")
        ):
            raise ValueError(f"invalid Rust path for {name}: {rust!r}")
        if kind == "class":
            methods = [method.get("name") for method in export.get("methods", [])]
            if len(methods) != len(set(methods)):
                raise ValueError(f"duplicate methods on Python class {name}")
            for method in export.get("methods", []):
                # A getter is a read-only attribute, a #[getter] in Rust.
                if method.get("kind", "getter") != "getter" or (
                    "kind" in method and method.get("args")
                ):
                    raise ValueError(
                        f"method {name}.{method.get('name')} must be a plain "
                        "method or a getter without arguments"
                    )
        if kind == "exception" and export.get("base") not in {
            "Exception",
            *[
                item["name"]
                for item in python["exports"]
                if item["kind"] == "exception"
            ],
        }:
            raise ValueError(f"Python exception {name} must derive from Exception")
    if len(names) != len(set(names)):
        raise ValueError("duplicate Python exports in bindings.yaml")


def _validate_operations(definition):
    python = definition["python"]
    classes = {
        export["name"]: {method["name"] for method in export.get("methods", [])}
        for export in python["exports"]
        if export["kind"] == "class"
    }
    exports = {export["name"] for export in python["exports"]}
    r_functions = {
        function["name"]
        for group in definition["r"]["groups"]
        for function in group["functions"]
    }
    # The command line calls the facade directly and pairs no native export:
    # each of its commands lists the operations it reaches.
    for operation, hosts in definition["operations"].items():
        if not isinstance(hosts, dict) or not set(hosts) <= {"python", "r"}:
            raise ValueError(f"operation {operation} has invalid host mapping")
        for reference in hosts.get("python", []):
            if "." in reference:
                owner, _, member = reference.partition(".")
                if owner not in classes or member not in classes[owner]:
                    raise ValueError(
                        f"operation {operation} references absent Python "
                        f"export member {reference}"
                    )
            elif reference not in exports:
                raise ValueError(
                    f"operation {operation} references absent Python export {reference}"
                )
        for reference in hosts.get("r", []):
            if reference not in r_functions:
                raise ValueError(
                    f"operation {operation} references absent R export {reference}"
                )
    host_only = definition["host_only"]
    if not isinstance(host_only, dict) or set(host_only) != {"python", "r"}:
        raise ValueError("host_only must contain python and r lists")
    for reference in host_only["python"]:
        if "." in reference:
            owner, _, member = reference.partition(".")
            if owner not in classes or member not in classes[owner]:
                raise ValueError(
                    f"host_only references absent Python export member {reference}"
                )
        elif reference not in exports:
            raise ValueError(f"host_only references absent Python export {reference}")
    for reference in host_only["r"]:
        if reference not in r_functions:
            raise ValueError(f"host_only references absent R export {reference}")
    _validate_pairing(definition, r_functions)


def _validate_pairing(definition, r_functions):
    """Every native export has its counterpart in the other host."""
    operations = definition["operations"]
    for operation, hosts in operations.items():
        if not hosts.get("python") or not hosts.get("r"):
            raise ValueError(
                f"operation {operation} must name both a Python and an R export"
            )
    paired_python = {ref for hosts in operations.values() for ref in hosts["python"]}
    paired_r = {ref for hosts in operations.values() for ref in hosts["r"]}
    python_members = set()
    for export in definition["python"]["exports"]:
        if export["kind"] in {"function", "constant"}:
            python_members.add(export["name"])
        elif export["kind"] == "class":
            python_members.update(
                f"{export['name']}.{method['name']}"
                for method in export.get("methods", [])
            )
    host_only = definition["host_only"]
    unpaired = sorted(python_members - paired_python - set(host_only["python"]))
    if unpaired:
        raise ValueError(
            f"Python exports without an R counterpart: {', '.join(unpaired)}"
        )
    unpaired = sorted(r_functions - paired_r - set(host_only["r"]))
    if unpaired:
        raise ValueError(
            f"R exports without a Python counterpart: {', '.join(unpaired)}"
        )


def _validate_r(definition):
    r = definition["r"]
    if not isinstance(r, dict) or set(r) != {"module", "registration", "groups"}:
        raise ValueError("R definition must contain module, registration and groups")
    if (
        r["module"] != "yamaa"
        or r["registration"] != (R_SOURCE / "lib.rs").relative_to(ROOT).as_posix()
    ):
        raise ValueError("unexpected R module or registration path")
    groups = r["groups"]
    if not isinstance(groups, list) or not groups:
        raise ValueError("R groups must be a nonempty list")
    modules = set()
    names = set()
    for group in groups:
        if not isinstance(group, dict) or set(group) != {
            "module",
            "source",
            "functions",
        }:
            raise ValueError("R group must contain module, source and functions")
        module = group["module"]
        if not isinstance(module, str) or not _NAME.fullmatch(module):
            raise ValueError(f"invalid R module name: {module!r}")
        if module in modules:
            raise ValueError(f"duplicate R module: {module}")
        modules.add(module)
        source = R_SOURCE / ("lib.rs" if module == r["module"] else f"{module}.rs")
        if (
            group["source"] != source.relative_to(ROOT).as_posix()
            or not source.is_file()
        ):
            raise ValueError(f"invalid R source for module {module}")
        functions = group["functions"]
        if not isinstance(functions, list) or not functions:
            raise ValueError(f"R module {module} functions must be a nonempty list")
        for function in functions:
            if not isinstance(function, dict) or set(function) != {
                "name",
                "args",
                "returns",
            }:
                raise ValueError("R function must contain name, args and returns")
            name = function["name"]
            if (
                not isinstance(name, str)
                or not _R_NAME.fullmatch(name)
                or name in _R_RESERVED
            ):
                raise ValueError(f"invalid R function name: {name!r}")
            if name in names:
                raise ValueError(f"duplicate R function: {name}")
            names.add(name)
            args = function["args"]
            if not isinstance(args, dict):
                raise ValueError(f"R function {name} args must be a mapping")
            for argument, kind in args.items():
                if (
                    not isinstance(argument, str)
                    or not _R_NAME.fullmatch(argument)
                    or argument in _R_RESERVED
                ):
                    raise ValueError(f"invalid R argument name: {argument!r}")
                if not isinstance(kind, str):
                    raise ValueError(f"R argument {name}.{argument} type must be text")
                kind, default = _split_default(kind)
                allowed_defaults = {
                    "bool": {"True", "False"},
                    "robj": {"None"},
                }.get(kind, set())
                if kind not in _R_TYPES or (
                    default is not None and default not in allowed_defaults
                ):
                    raise ValueError(f"unsupported R argument type/default: {kind!r}")
            returns = function["returns"]
            if not isinstance(returns, str) or returns not in _R_TYPES:
                raise ValueError(f"unsupported R return type for {name}: {returns!r}")
    if r["module"] not in modules:
        raise ValueError("R groups must declare the root module")


# --- Type expressions ----------------------------------------------------------


def _parse_type(text, pos=0):
    """Parse one type expression; returns ``(node, next_pos)``."""
    match = _NAME.match(text, pos)
    if match is None:
        raise ValueError(f"invalid type expression: {text!r}")
    name = match.group(0)
    pos = match.end()
    if pos < len(text) and text[pos] == "<":
        if name not in _GENERIC_TYPES:
            raise ValueError(f"unsupported generic type in bindings.yaml: {name}")
        args = []
        pos += 1
        while True:
            node, pos = _parse_type(text, pos)
            args.append(node)
            if pos < len(text) and text[pos] == ",":
                pos += 1
                while pos < len(text) and text[pos] == " ":
                    pos += 1
                continue
            if pos < len(text) and text[pos] == ">":
                pos += 1
                break
            raise ValueError(f"invalid type expression: {text!r}")
        if name in ("optional", "list") and len(args) != 1:
            raise ValueError(f"{name} takes exactly one type argument: {text!r}")
        return (name, args), pos
    return ("named", name), pos


def _type_node(text):
    node, pos = _parse_type(text)
    if pos != len(text):
        raise ValueError(f"invalid type expression: {text!r}")
    return node


def _python_type(node, definition, classes):
    kind = node[0]
    if kind == "named":
        name = node[1]
        if name in _SCALAR_TYPES:
            return _SCALAR_TYPES[name]
        if name in classes:
            return name
        raise ValueError(f"unknown type token in bindings.yaml: {name}")
    if kind == "optional":
        return _python_type(node[1][0], definition, classes) + " | None"
    if kind == "list":
        return f"list[{_python_type(node[1][0], definition, classes)}]"
    if kind == "tuple":
        inner = ", ".join(_python_type(arg, definition, classes) for arg in node[1])
        return f"tuple[{inner}]"
    raise ValueError(f"unsupported type node: {node!r}")


def _split_default(text):
    """Split ``type = literal`` at angle-bracket depth zero."""
    depth = 0
    for index, char in enumerate(text):
        if char == "<":
            depth += 1
        elif char == ">":
            depth -= 1
        elif char == "=" and depth == 0:
            literal = text[index + 1 :].strip()
            rendered = {"None": "None", "false": "False", "true": "True"}.get(
                literal, literal
            )
            return text[:index].strip(), rendered
    return text, None


def _split_top_level(text):
    """Split ``text`` on commas at angle-bracket/paren depth zero.

    Generic types such as ``HashMap<String, i32>`` contain commas that do
    not separate arguments.
    """
    parts = []
    depth = 0
    current = []
    for char in text:
        if char in "<([{":
            depth += 1
        elif char in ">)]}":
            depth -= 1
        if char == "," and depth == 0:
            parts.append("".join(current))
            current = []
        else:
            current.append(char)
    parts.append("".join(current))
    return parts


def _python_args(args, definition, classes):
    rendered = []
    for name, spec in (args or {}).items():
        type_text, default = _split_default(spec)
        piece = f"{name}: {_python_type(_type_node(type_text), definition, classes)}"
        if default is not None:
            piece += f" = {default}"
        rendered.append(piece)
    return ", ".join(rendered)


# --- Reconciliation against the handwritten PyO3 surface -----------------------

_CHAR = re.compile(r"'(?:\\.|[^'\\])'")


def _string_end(text, i):
    char = text[i]
    if char == '"':
        j = i + 1
        while j < len(text):
            if text[j] == "\\":
                j += 2
            elif text[j] == '"':
                return j + 1
            else:
                j += 1
        raise ValueError("unterminated string in yamaa-python source")
    if char == "'":
        match = _CHAR.match(text, i)
        return match.end() if match else None
    if char == "r" and i + 1 < len(text) and text[i + 1] == '"':
        found = text.find('"', i + 2)
        if found == -1:
            raise ValueError("unterminated raw string in yamaa-python source")
        return found + 1
    return None


def _strip_rust(text):
    """Blank comments and literal contents so brace matching is structural."""
    out = []
    i = 0
    end = len(text)
    while i < end:
        if text.startswith("//", i):
            newline = text.find("\n", i)
            if newline == -1:
                break
            out.append("\n")
            i = newline + 1
        elif text.startswith("/*", i):
            close = text.find("*/", i + 2)
            if close == -1:
                raise ValueError("unterminated block comment in yamaa-python source")
            out.append(" ")
            i = close + 2
        else:
            stop = _string_end(text, i)
            if stop is not None:
                out.append('""' if text[i] in '"r' else "''")
                i = stop
            else:
                out.append(text[i])
                i += 1
    return "".join(out)


def _block(text, open_at):
    """Return ``(body, next_pos)`` for the brace block opening at `open_at`."""
    assert text[open_at] == "{"
    depth = 0
    i = open_at
    while i < len(text):
        char = text[i]
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return text[open_at + 1 : i], i + 1
        i += 1
    raise ValueError("unbalanced braces in yamaa-python source")


def _method_names(block):
    names = []
    depth = 0
    i = 0
    pattern = re.compile(r"(?:pub(?:\(crate\))?\s+)?fn\s+([A-Za-z_][A-Za-z0-9_]*)")
    while i < len(block):
        char = block[i]
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
        elif depth == 0:
            match = pattern.match(block, i)
            if match:
                # PyO3 installs these as C GC slots, not Python attributes.
                # Every Python-callable method still belongs in bindings.yaml.
                if match.group(1) not in {"__traverse__", "__clear__"}:
                    names.append(match.group(1))
                i = match.end()
                continue
        i += 1
    return names


def _reconcile(definition):
    """Fail when bindings.yaml omits or invents handwritten PyO3 surface."""
    src = RUST_TARGET.parent
    classes = {}
    exceptions = {}
    functions = {}
    methods = {}
    getters = {}
    for path in sorted(src.glob("*.rs")):
        if path.name == "lib.rs":
            continue
        raw = path.read_text(encoding="utf-8")
        for name, struct in re.findall(
            r'#\[pyclass\([^\]]*name\s*=\s*"([^"]+)"[^\]]*\)\]\s*pub struct (\w+)',
            raw,
        ):
            classes[name] = (path.stem, struct)
        for name in re.findall(r"create_exception!\(\s*\w+,\s*(\w+),", raw):
            exceptions[name] = path.stem
        for name in re.findall(
            r"#\[pyfunction\]\s*(?:#\[pyo3\([^\]]*\)\]\s*)?pub fn (\w+)",
            raw,
        ):
            functions[name] = path.stem
        text = _strip_rust(raw)
        for match in re.finditer(r"#\[pymethods\]\s*impl\s+(\w+)\s*\{", text):
            body, _ = _block(text, match.end() - 1)
            methods.setdefault(match.group(1), set()).update(_method_names(body))
            getters.setdefault(match.group(1), set()).update(
                re.findall(
                    r"#\[getter\]\s*(?:#\[[^\]]*\]\s*)*"
                    r"(?:pub(?:\(crate\))?\s+)?fn\s+(\w+)",
                    body,
                )
            )
    declared = {export["name"]: export for export in definition["python"]["exports"]}
    by_kind = {}
    for export in declared.values():
        by_kind.setdefault(export["kind"], {})[export["name"]] = export
    if set(by_kind.get("class", {})) != set(classes):
        raise ValueError(
            "bindings.yaml Python classes differ from #[pyclass] registrations: "
            f"{sorted(by_kind.get('class', {}))} != {sorted(classes)}"
        )
    for name, export in by_kind.get("class", {}).items():
        module, struct = classes[name]
        if export["rust"] != f"{module}::{struct}":
            raise ValueError(
                f"bindings.yaml class {name} names the wrong Rust path: "
                f"{export['rust']} != {module}::{struct}"
            )
        declared_methods = {method["name"] for method in export.get("methods", [])}
        if declared_methods != methods.get(struct, set()):
            raise ValueError(
                f"bindings.yaml methods for {name} differ from #[pymethods]: "
                f"{sorted(declared_methods)} != {sorted(methods.get(struct, set()))}"
            )
        declared_getters = {
            method["name"]
            for method in export.get("methods", [])
            if method.get("kind") == "getter"
        }
        if declared_getters != getters.get(struct, set()):
            raise ValueError(
                f"bindings.yaml getters for {name} differ from #[getter]: "
                f"{sorted(declared_getters)} != {sorted(getters.get(struct, set()))}"
            )
    if set(by_kind.get("exception", {})) != set(exceptions):
        raise ValueError(
            "bindings.yaml Python exceptions differ from create_exception!: "
            f"{sorted(by_kind.get('exception', {}))} != {sorted(exceptions)}"
        )
    if set(by_kind.get("function", {})) != set(functions):
        raise ValueError(
            "bindings.yaml Python functions differ from #[pyfunction]: "
            f"{sorted(by_kind.get('function', {}))} != {sorted(functions)}"
        )
    for kind, found in (("exception", exceptions), ("function", functions)):
        for name, export in by_kind.get(kind, {}).items():
            if export["rust"] != f"{found[name]}::{name}":
                raise ValueError(
                    f"bindings.yaml {kind} {name} names the wrong Rust path: "
                    f"{export['rust']} != {found[name]}::{name}"
                )


def _reconcile_r(definition):
    """Reconcile every extendr function, including positional wire signatures."""
    found = {}
    pattern = re.compile(
        r"#\[extendr\]\s*(?:pub\s+)?fn\s+(\w+)\s*\((.*?)\)\s*->\s*([^{}]+)\{",
        re.S,
    )
    for path in sorted(R_SOURCE.glob("*.rs")):
        source = _strip_rust(path.read_text(encoding="utf-8"))
        functions = {}
        for match in pattern.finditer(source):
            name, arguments, returns = match.groups()
            args = []
            for argument in _split_top_level(arguments):
                if not argument.strip():
                    continue
                key, separator, kind = argument.partition(":")
                if not separator:
                    raise ValueError(f"unsupported extendr argument: {argument!r}")
                args.append((key.strip(), re.sub(r"\s+", "", kind)))
            functions[name] = (args, re.sub(r"\s+", "", returns))
        if len(re.findall(r"#\[extendr(?:\([^]]*\))?\]", source)) != len(functions):
            raise ValueError(f"unsupported extendr signature in {path.name}")
        if functions:
            found[path.relative_to(ROOT).as_posix()] = functions
    groups = definition["r"]["groups"]
    if {group["source"] for group in groups} != set(found):
        raise ValueError("R groups differ from the handwritten #[extendr] modules")
    for group in groups:
        raw = (ROOT / group["source"]).read_text(encoding="utf-8")
        include = f'include!("generated/{group["module"]}.rs");'
        if raw.count(include) != 1 or "extendr_module!" in _strip_rust(raw):
            raise ValueError(
                f"R module {group['module']} must include its generated registration"
            )
        functions = found[group["source"]]
        if {function["name"] for function in group["functions"]} != set(functions):
            raise ValueError(
                f"R functions in {group['module']} differ from #[extendr] functions"
            )
        for function in group["functions"]:
            args, returns = functions[function["name"]]
            expected = list(function["args"].items())
            if len(args) != len(expected) or any(
                name != declared_name
                or kind
                not in {
                    re.sub(r"\s+", "", rust_type)
                    for rust_type in _R_TYPES[_split_default(declared_type)[0]]
                }
                for (name, kind), (declared_name, declared_type) in zip(args, expected)
            ):
                raise ValueError(f"R argument signature differs for {function['name']}")
            allowed_returns = {
                re.sub(r"\s+", "", kind) for kind in _R_TYPES[function["returns"]]
            }
            if returns not in allowed_returns:
                raise ValueError(f"R return signature differs for {function['name']}")


def _render_r_registration(group, root):
    lines = [*_RUST_HEADER, "extendr_module! {", f"    mod {group['module']};"]
    lines.extend(f"    fn {function['name']};" for function in group["functions"])
    if group["module"] == root["module"]:
        lines.extend(
            f"    use {child['module']};"
            for child in root["groups"]
            if child["module"] != root["module"]
        )
    return "\n".join([*lines, "}", ""])


def _render_r_wrappers(definition):
    """The private native-call wrappers, then the interface handshake."""
    lines = [*_PYI_HEADER, ""]
    defaults = {"None": "NULL", "True": "TRUE", "False": "FALSE"}
    for group in definition["r"]["groups"]:
        for function in group["functions"]:
            name = function["name"]
            arguments = []
            for argument, spec in function["args"].items():
                _, default = _split_default(spec)
                arguments.append(
                    argument if default is None else f"{argument} = {defaults[default]}"
                )
            args = ", ".join(arguments)
            values = ", ".join(function["args"])
            suffix = f", {values}" if values else ""
            lines += [
                f".native_{name} <- function({args}) {{",
                f"  .Call(wrap__{name}{suffix})",
                "}",
                "",
            ]
    lines += bindings_handshake.r_lines(definition)
    return "\n".join([*lines, ""])


