"""Committed API inventory for the `yamaa` facade crate.

The committed ``rust/crates/yamaa/public-api.txt`` lists exactly the facade
surface of crate ``yamaa`` (one ``path: declaration`` line per public item, in
``cargo public-api`` style) so any surface change shows up as inventory drift.
The pinned stable toolchain emits no rustdoc JSON and the repository takes no
``cargo-public-api`` dependency, so this generator parses the facade sources
directly with the standard library only.

Scope is the facade crate alone: public modules reachable from ``lib.rs`` plus
the crate-root re-exports. The private ``internal`` bridge module, ``cfg(test)``
modules, ``pub(crate)``/``pub(super)`` items, the impl blocks of types that a
module declares without plain ``pub``, and function bodies are not surface and
are excluded; ``pub use`` re-exports (including the re-exported
Arrow types) are recorded because they are addressable API. ``const``/``static``
values are dropped (only name and type are surface) while type-alias targets
are kept. Any unrecognised top-level construct fails loudly so new syntax gets
explicit parser support instead of silent omission.
"""

import argparse
import re

from tools.paths import WORKSPACE

CRATE = WORKSPACE / "crates/yamaa"
SRC = CRATE / "src"
TARGET = CRATE / "public-api.txt"

_HEADER = [
    "# Generated by tools/packaging/generate_facade_api.py --write. Do not edit.",
    "# Facade surface of crate `yamaa`: one line per public item, `cargo public-api` style.",
    "# Sources: rust/crates/yamaa/src/*.rs (public modules only; adapter and core internals excluded).",
]

_CHAR = re.compile(r"'(?:\\.|[^'\\])'")
_SEMI_ITEM = re.compile(r"(?:pub\s*(?:\([^)]*\))?\s+)?(use|const|static|type)\b")
_ITEM_NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
# A type declared without plain `pub`: private, or restricted as `pub(crate)`.
_PRIVATE_TYPE = re.compile(
    r"(?:pub\s*\([^)]*\)\s*)?(?:unsafe\s+)?(?:struct|enum|union|trait|type)\s+(\w+)"
)


def _squash(text):
    return re.sub(r"\s+", " ", text).strip()


def _decl(text):
    squashed = _squash(text).replace("crate::", "yamaa::")
    return squashed.replace("( ", "(").replace(" )", ")").replace(",)", ")")


def _path(parts):
    return "::".join(parts)


def _quoted_end(text, start):
    i = start + 1
    end = len(text)
    while i < end:
        char = text[i]
        if char == "\\":
            i += 2
        elif char == '"':
            return i + 1
        else:
            i += 1
    raise ValueError("unterminated string in facade source")


def _raw_end(text, start):
    j = start + 1
    while j < len(text) and text[j] == "#":
        j += 1
    if j >= len(text) or text[j] != '"':
        return None
    closer = '"' + "#" * (j - start - 1)
    found = text.find(closer, j + 1)
    if found == -1:
        raise ValueError("unterminated raw string in facade source")
    return found + len(closer)


def _string_end(text, i):
    """Index just past a string/char literal starting at `i`, else None."""
    char = text[i]
    if char == '"':
        return _quoted_end(text, i)
    if char == "'":
        match = _CHAR.match(text, i)
        return match.end() if match else None
    if char == "r" and i + 1 < len(text):
        return _raw_end(text, i)
    if char == "b" and i + 1 < len(text):
        nxt = text[i + 1]
        if nxt == '"':
            return _quoted_end(text, i + 1)
        if nxt == "'":
            match = _CHAR.match(text, i + 1)
            return match.end() if match else None
        if nxt == "r":
            return _raw_end(text, i + 1)
    return None


def _strip_comments(text):
    out = []
    i = 0
    end = len(text)
    while i < end:
        if text.startswith("//", i):
            newline = text.find("\n", i)
            if newline == -1:
                break
            out.append("\n")
            i = newline + 1
        elif text.startswith("/*", i):
            depth = 0
            i += 2
            while i < end:
                if text.startswith("/*", i):
                    depth += 1
                    i += 2
                elif text.startswith("*/", i):
                    if depth == 0:
                        break
                    depth -= 1
                    i += 2
                else:
                    i += 1
            if i >= end:
                raise ValueError("unterminated block comment in facade source")
            out.append(" ")
            i += 2
        else:
            stop = _string_end(text, i)
            if stop is not None:
                out.append(text[i:stop])
                i = stop
            else:
                out.append(text[i])
                i += 1
    return "".join(out)


def _skip_ws(text, i):
    while i < len(text) and text[i] in " \t\n\r":
        i += 1
    return i


def _scan_balanced(text, start, opener, closer):
    """Index just past the `closer` matching the opener at `start`."""
    assert text[start] == opener
    depth = 0
    i = start
    end = len(text)
    while i < end:
        stop = _string_end(text, i)
        if stop is not None:
            i = stop
            continue
        char = text[i]
        if char == opener:
            depth += 1
        elif char == closer:
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    raise ValueError("unbalanced delimiters in facade source")


def _split_top(text, sep):
    """Split on `sep` at nesting depth zero.

    Angle brackets join the tracked kinds with a small guard so generic
    argument lists (``BTreeMap<String, ContextValue>``) do not split, while
    ``->``, ``=>``, ``>=``, ``<=`` and ``<<`` never unbalance the depth.
    Strings are skipped so separators inside them never split.
    """
    parts = []
    depth = {"(": 0, "[": 0, "{": 0, "<": 0}
    pairs = {")": "(", "]": "[", "}": "{"}
    current = []
    i = 0
    end = len(text)
    while i < end:
        stop = _string_end(text, i)
        if stop is not None:
            current.append(text[i:stop])
            i = stop
            continue
        char = text[i]
        prev = text[i - 1] if i > 0 else ""
        nxt = text[i + 1] if i + 1 < end else ""
        if char in "([{":
            depth[char] += 1
        elif char in ")]}":
            depth[pairs[char]] -= 1
        elif char == "<" and nxt not in "=<":
            depth["<"] += 1
        elif char == ">" and prev not in "-=" and depth["<"] > 0:
            depth["<"] -= 1
        elif char == sep and all(value == 0 for value in depth.values()):
            parts.append("".join(current))
            current = []
            i += 1
            continue
        current.append(char)
        i += 1
    parts.append("".join(current))
    return parts


def _peel_attrs(text):
    """Split leading `#[...]` attributes from item text."""
    attrs = []
    i = _skip_ws(text, 0)
    while text.startswith("#[", i):
        stop = _scan_balanced(text, i + 1, "[", "]")
        attrs.append(_squash(text[i:stop]))
        i = _skip_ws(text, stop)
    return attrs, text[i:]


def _is_test_cfg(attrs):
    # Only exact test gates count: #[cfg(test)], or `test` as a top-level
    # operand of #[cfg(all(...))]. A looser match would also drop
    # #[cfg(not(test))] or features named like "test-utils", hiding real
    # surface items from the inventory.
    for attr in attrs:
        body = attr.strip()
        if body == "#[cfg(test)]":
            return True
        match = re.fullmatch(r"#\[cfg\(all\((.*)\)\)\]", body, re.DOTALL)
        if match is None:
            continue
        depth = 0
        part = ""
        for char in match.group(1):
            if char == "(":
                depth += 1
            elif char == ")":
                depth -= 1
            if char == "," and depth == 0:
                if part.strip() == "test":
                    return True
                part = ""
            else:
                part += char
        if part.strip() == "test":
            return True
    return False


def _attr_markers(attrs):
    markers = []
    for attr in attrs:
        if attr == "#[non_exhaustive]":
            markers.append("[non_exhaustive]")
        elif attr.startswith("#[derive(") and attr.endswith("]"):
            inner = attr[len("#[derive(") : -2]
            names = sorted(part.strip() for part in inner.split(",") if part.strip())
            markers.append("[derive(" + ", ".join(names) + ")]")
        elif attr.startswith("#[cfg(") and attr.endswith("]"):
            markers.append("[" + attr[2:-1] + "]")
    return sorted(markers)


def _markers_suffix(attrs):
    markers = _attr_markers(attrs)
    return (" " + " ".join(markers)) if markers else ""


def _item_end(text, start, semi_only):
    paren = brack = brace = 0
    i = start
    end = len(text)
    while i < end:
        stop = _string_end(text, i)
        if stop is not None:
            i = stop
            continue
        char = text[i]
        if char == "(":
            paren += 1
        elif char == ")":
            paren -= 1
        elif char == "[":
            brack += 1
        elif char == "]":
            brack -= 1
        elif char == "{":
            if not semi_only and paren == 0 and brack == 0 and brace == 0:
                return _scan_balanced(text, i, "{", "}")
            brace += 1
        elif char == "}":
            brace -= 1
        elif char == ";" and paren == 0 and brack == 0 and brace == 0:
            return i + 1
        i += 1
    raise ValueError("unterminated item in facade source")


def _split_items(text):
    """Yield `(attrs, body)` for each top-level item in module text."""
    items = []
    i = 0
    end = len(text)
    while True:
        i = _skip_ws(text, i)
        if i >= end:
            return items
        if text.startswith("#![", i):
            i = _scan_balanced(text, i + 2, "[", "]")
            continue
        attrs = []
        while text.startswith("#[", i):
            stop = _scan_balanced(text, i + 1, "[", "]")
            attrs.append(_squash(text[i:stop]))
            i = _skip_ws(text, stop)
        i = _skip_ws(text, i)
        if i >= end:
            return items
        start = i
        semi_only = _SEMI_ITEM.match(text, start) is not None
        i = _item_end(text, start, semi_only)
        items.append((attrs, text[start:i]))


def _head_split(body):
    """Split an item into `(head, kind, tail)` at its first `{` or `;`."""
    paren = brack = 0
    i = 0
    end = len(body)
    while i < end:
        stop = _string_end(body, i)
        if stop is not None:
            i = stop
            continue
        char = body[i]
        if char == "(":
            paren += 1
        elif char == ")":
            paren -= 1
        elif char == "[":
            brack += 1
        elif char == "]":
            brack -= 1
        elif char == "{" and paren == 0 and brack == 0:
            return body[:i], "{", body[i:]
        elif char == ";" and paren == 0 and brack == 0:
            return body[:i], ";", body[i:]
        i += 1
    return body, "", ""


def _bare_equals(stmt, start=0):
    """Index of the assignment `=` at depth zero, else None."""
    paren = brack = brace = 0
    i = start
    end = len(stmt)
    while i < end:
        stop = _string_end(stmt, i)
        if stop is not None:
            i = stop
            continue
        char = stmt[i]
        if char in "([{":
            if char == "(":
                paren += 1
            elif char == "[":
                brack += 1
            else:
                brace += 1
        elif char in ")]}":
            if char == ")":
                paren -= 1
            elif char == "]":
                brack -= 1
            else:
                brace -= 1
        elif (
            char == "="
            and paren == 0
            and brack == 0
            and brace == 0
            and (i == 0 or stmt[i - 1] not in "=!<>+-*/&|^:")
            and (i + 1 >= end or stmt[i + 1] not in "=>")
        ):
            return i
        i += 1
    return None


def _expand_use(tree):
    """Expand a use-tree into `(source, alias)` pairs."""
    found = []

    def rec(base, node):
        node = node.strip()
        open_at = node.find("{")
        if open_at == -1:
            rename = re.match(
                r"^(.*?)\s+as\s+([A-Za-z_][A-Za-z0-9_]*)$", node, re.DOTALL
            )
            if rename:
                found.append((_squash(base + rename.group(1)), rename.group(2)))
            elif node.endswith("::*"):
                found.append((_squash(base + node[:-3]), "*"))
            else:
                alias = node.split("::")[-1]
                if alias == "self":
                    alias = (base + node).rstrip(":").split("::")[-2]
                found.append((_squash(base + node), alias))
            return
        head = node[:open_at]
        close = _scan_balanced(node, open_at, "{", "}")
        inner = node[open_at + 1 : close - 1]
        if node[close:].strip():
            raise ValueError(f"unsupported use tree: {tree!r}")
        for part in _split_top(inner, ","):
            if part.strip():
                rec(base + head, part)

    rec("", tree)
    return found


def _resolve_source(modpath, source, modules):
    """Resolve a `pub use` source to a full path, or None when external."""
    segments = source.split("::")
    first = segments[0]
    if first == "crate":
        return ("yamaa",) + tuple(segments[1:])
    if first == "self":
        return modpath + tuple(segments[1:])
    if first == "super":
        depth = 0
        while depth < len(segments) and segments[depth] == "super":
            depth += 1
        if depth >= len(modpath):
            raise ValueError(f"unsupported use source: {source!r}")
        return modpath[: len(modpath) - depth] + tuple(segments[depth:])
    if first in modules:
        return modules[first] + tuple(segments[1:])
    return None


def _parse_field(path, field, entries):
    attrs, rest = _peel_attrs(field)
    rest = rest.strip()
    if not rest:
        return
    if re.match(r"pub\s*\(", rest):
        return
    match = re.match(r"pub\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*(.+)$", rest, re.DOTALL)
    if match:
        name, type_text = match.group(1), _decl(match.group(2))
        entries.append(
            f"{_path(path + (name,))}: pub {name}: {type_text}{_markers_suffix(attrs)}"
        )
        return
    if re.match(r"[A-Za-z_][A-Za-z0-9_]*\s*:", rest):
        return
    raise ValueError(f"unrecognised struct field: {rest[:80]!r}")


def _parse_tuple_field(path, index, field, entries):
    _, rest = _peel_attrs(field)
    rest = rest.strip()
    if not rest:
        return
    if re.match(r"pub\s*\(", rest):
        return
    if rest.startswith("pub ") or rest == "pub":
        type_text = _decl(rest[3:].strip())
        entries.append(f"{_path(path + (str(index),))}: pub {index}: {type_text}")
        return
    if re.match(r"[A-Za-z_]", rest):
        return
    raise ValueError(f"unrecognised tuple field: {rest[:80]!r}")


def _parse_member(path, attrs, body, entries, in_trait):
    suffix = _markers_suffix(attrs)
    if _is_test_cfg(attrs):
        return
    stripped = body.strip()
    if not in_trait and re.match(r"pub\s*\(", stripped):
        return
    match = re.match(r"(pub\s+)?fn\s+([A-Za-z_][A-Za-z0-9_]*)", stripped)
    if match and (in_trait or match.group(1)):
        head, kind, _ = _head_split(stripped)
        if not kind:
            raise ValueError(f"unrecognised function item: {stripped[:80]!r}")
        marker = ""
        if in_trait:
            marker = " [default]" if kind == "{" else " [required]"
        entries.append(
            f"{_path(path + (match.group(2),))}: {_decl(head)}{marker}{suffix}"
        )
        return
    match = re.match(r"(pub\s+)?(type|const)\s+([A-Za-z_][A-Za-z0-9_]*)", stripped)
    if match and (in_trait or match.group(1)):
        if match.group(2) == "type":
            statement = stripped.rstrip().rstrip(";")
            marker = (
                " [default]" if _bare_equals(statement) is not None else " [required]"
            )
            entries.append(
                f"{_path(path + (match.group(3),))}: {_decl(statement)}{marker}{suffix}"
            )
            return
        head = stripped
        if head.rstrip().endswith(";"):
            head = head.rstrip()[:-1]
        equals = _bare_equals(head)
        marker = " [default]" if equals is not None else " [required]"
        decl = head[:equals] if equals is not None else head
        entries.append(
            f"{_path(path + (match.group(3),))}: {_decl(decl)}{marker}{suffix}"
        )
        return
    if not in_trait and re.match(
        r"(?:fn|type|const|static|struct|enum|trait|mod|use|extern)\b", stripped
    ):
        return
    raise ValueError(f"unrecognised impl/trait member: {stripped[:80]!r}")


def _parse_pub_item(modpath, attrs, body, entries, state):
    suffix = _markers_suffix(attrs)
    path = _path(modpath)
    if body.startswith("pub mod "):
        head, kind, tail = _head_split(body)
        name = re.match(r"pub\s+mod\s+(\w+)", head).group(1)
        entries.append(f"{path}: pub mod {name}{suffix}")
        if kind == ";":
            _parse_file_module(modpath, name, entries, state)
        elif kind == "{":
            modules = state["modules"]
            if name in modules:
                raise ValueError(f"duplicate module: {name!r}")
            modules[name] = modpath + (name,)
            _parse_module(modpath + (name,), tail[1:-1], entries, state)
        else:
            raise ValueError(f"unrecognised module item: {body[:80]!r}")
        return
    if body.startswith("pub use "):
        statement = body[len("pub use ") :].rstrip()
        assert statement.endswith(";")
        for source, alias in _expand_use(statement[:-1]):
            resolved = _resolve_source(modpath, source, state["modules"])
            if resolved is None:
                if "::" not in source:
                    raise ValueError(f"unsupported use source: {source!r}")
                full = source
            else:
                if resolved[:-1] not in state["public"]:
                    raise ValueError(f"re-export from private module: {source!r}")
                full = _path(resolved)
            if alias == "*":
                entries.append(f"{path}: pub use {full}::*{suffix}")
            else:
                rename = "" if alias == full.split("::")[-1] else f" as {alias}"
                entries.append(
                    f"{_path(modpath + (alias,))}: pub use {full}{rename}{suffix}"
                )
        return
    if body.startswith("pub struct "):
        head, kind, tail = _head_split(body)
        name = re.match(r"pub\s+struct\s+(\w+)", head).group(1)
        entries.append(f"{_path(modpath + (name,))}: {_decl(head)}{suffix}")
        if kind == "{":
            for field in _split_top(tail[1:-1], ","):
                _parse_field(modpath + (name,), field, entries)
        elif kind == ";":
            paren_at = _tuple_paren(head, name)
            if paren_at != -1:
                inner = head[paren_at + 1 : head.rfind(")")]
                for index, field in enumerate(_split_top(inner, ",")):
                    _parse_tuple_field(modpath + (name,), index, field, entries)
        else:
            raise ValueError(f"unrecognised struct item: {body[:80]!r}")
        return
    if body.startswith("pub enum "):
        head, kind, tail = _head_split(body)
        if kind != "{":
            raise ValueError(f"unrecognised enum item: {body[:80]!r}")
        name = re.match(r"pub\s+enum\s+(\w+)", head).group(1)
        entries.append(f"{_path(modpath + (name,))}: {_decl(head)}{suffix}")
        for variant in _split_top(tail[1:-1], ","):
            vattrs, rest = _peel_attrs(variant)
            rest = rest.strip()
            if not rest or _is_test_cfg(vattrs):
                continue
            vname = _ITEM_NAME.match(rest).group(0)
            entries.append(
                f"{_path(modpath + (name, vname))}: {_decl(rest)}{_markers_suffix(vattrs)}"
            )
        return
    if re.match(r"pub\s+(unsafe\s+)?trait\s+", body):
        head, kind, tail = _head_split(body)
        if kind != "{":
            raise ValueError(f"unrecognised trait item: {body[:80]!r}")
        name = re.match(r"pub\s+(?:unsafe\s+)?trait\s+(\w+)", head).group(1)
        entries.append(f"{_path(modpath + (name,))}: {_decl(head)}{suffix}")
        for mattrs, mbody in _split_items(tail[1:-1]):
            _parse_member(modpath + (name,), mattrs, mbody, entries, in_trait=True)
        return
    match = re.match(
        r"pub\s+(?:unsafe\s+|async\s+|const\s+|extern\s+(?:\"[^\"]*\"\s+)?)?fn\s+(\w+)",
        body,
    )
    if match:
        head, kind, _ = _head_split(body)
        if kind != "{":
            raise ValueError(f"unrecognised function item: {body[:80]!r}")
        entries.append(f"{_path(modpath + (match.group(1),))}: {_decl(head)}{suffix}")
        return
    match = re.match(r"pub\s+(const|static)\s+(\w+)", body)
    if match:
        statement = body.rstrip().rstrip(";")
        equals = _bare_equals(statement)
        decl = statement[:equals] if equals is not None else statement
        entries.append(f"{_path(modpath + (match.group(2),))}: {_decl(decl)}{suffix}")
        return
    match = re.match(r"pub\s+type\s+(\w+)", body)
    if match:
        statement = body.rstrip().rstrip(";")
        entries.append(
            f"{_path(modpath + (match.group(1),))}: {_decl(statement)}{suffix}"
        )
        return
    raise ValueError(f"unrecognised facade item: {body[:80]!r}")


def _tuple_paren(head, name):
    """Index of a tuple-struct field list paren, else -1."""
    depth = 0
    i = head.find(name) + len(name)
    while i < len(head):
        stop = _string_end(head, i)
        if stop is not None:
            i = stop
            continue
        char = head[i]
        if char == "<":
            depth += 1
        elif char == ">":
            depth -= 1
        elif char == "(" and depth == 0:
            return i
        i += 1
    return -1


def _strip_generics(text):
    """Remove one leading `<...>` generic parameter list, if present."""
    if not text.startswith("<"):
        return text
    depth = 0
    i = 0
    end = len(text)
    while i < end:
        stop = _string_end(text, i)
        if stop is not None:
            i = stop
            continue
        char = text[i]
        prev = text[i - 1] if i > 0 else ""
        nxt = text[i + 1] if i + 1 < end else ""
        if char == "<" and nxt not in "=<":
            depth += 1
        elif char == ">" and prev not in "-=" and depth > 0:
            depth -= 1
            if depth == 0:
                return text[i + 1 :].strip()
        i += 1
    raise ValueError(f"unbalanced generics: {text[:80]!r}")


def _private_types(text):
    """Names of the types a module declares without plain ``pub``.

    No path outside the crate names such a type, so an impl of it, inherent
    or trait, is not surface, whatever its members' visibility.
    """
    names = set()
    for attrs, body in _split_items(text):
        if _is_test_cfg(attrs):
            continue
        match = _PRIVATE_TYPE.match(body.strip())
        if match:
            names.add(match.group(1))
    return names


def _parse_impl(modpath, attrs, body, entries, private=frozenset()):
    suffix = _markers_suffix(attrs)
    if _is_test_cfg(attrs):
        return
    head, kind, tail = _head_split(body)
    if kind != "{" or not head.startswith("impl"):
        raise ValueError(f"unrecognised impl item: {body[:80]!r}")
    rest = head[len("impl") :].strip()
    trait = re.search(r"\sfor\s", rest)
    if trait:
        selfpart = re.split(r"\sfor\s", rest, maxsplit=1)[1]
        selfpart = re.split(r"\swhere\s", selfpart, maxsplit=1)[0].strip()
    else:
        selfpart = re.split(r"\swhere\s", _strip_generics(rest), maxsplit=1)[0].strip()
    if _self_name(selfpart, body) in private:
        return
    if not trait:
        for mattrs, mbody in _split_items(tail[1:-1]):
            _parse_member(
                modpath + (_self_name(selfpart, body),),
                mattrs,
                mbody,
                entries,
                in_trait=False,
            )
    entries.append(
        f"{_path(modpath + (_self_name(selfpart, body),))}: {_decl(head)}{suffix}"
    )


def _self_name(selfpart, body):
    match = _ITEM_NAME.match(selfpart.strip())
    if not match:
        raise ValueError(f"unsupported impl self type: {body[:80]!r}")
    return match.group(0)


def _module_file(modpath, name):
    return SRC.joinpath(*modpath[1:], f"{name}.rs")


def _parse_file_module(modpath, name, entries, state):
    modules = state["modules"]
    if name in modules:
        raise ValueError(f"duplicate module: {name!r}")
    modules[name] = modpath + (name,)
    if modpath in state["public"]:
        state["public"].add(modpath + (name,))
    target = _module_file(modpath, name)
    if not target.is_file():
        raise ValueError(f"missing module file: {target}")
    key = target.relative_to(SRC).as_posix()
    state["files"].add(key)
    _parse_module(
        modpath + (name,),
        _strip_comments(target.read_text(encoding="utf-8")),
        entries,
        state,
    )


def _parse_module(modpath, text, entries, state):
    private = _private_types(text)
    for attrs, body in _split_items(text):
        if _is_test_cfg(attrs):
            continue
        stripped = body.strip()
        if re.match(r"pub(?:\s|\()", stripped):
            if re.match(r"pub\s*\(", stripped):
                continue
            _parse_pub_item(modpath, attrs, stripped, entries, state)
        elif re.match(r"impl(?:\s|<)", stripped):
            _parse_impl(modpath, attrs, stripped, entries, private)
        elif re.match(
            r"(?:mod|use|fn|struct|enum|trait|const|static|type|extern)\b", stripped
        ):
            continue
        elif re.match(r"[A-Za-z_][A-Za-z0-9_]*\s*!", stripped):
            continue
        else:
            raise ValueError(f"unrecognised facade item: {stripped[:80]!r}")


def _discover(modpath, text, state):
    for attrs, body in _split_items(text):
        if _is_test_cfg(attrs):
            continue
        match = re.match(r"(pub\s+)?mod\s+(\w+)", body)
        if not match:
            continue
        _, kind, tail = _head_split(body)
        if kind == "{":
            _discover(modpath + (match.group(2),), tail[1:-1], state)
        elif kind == ";":
            target = _module_file(modpath, match.group(2))
            state["allmods"].append(target)
            _discover(
                modpath + (match.group(2),),
                _strip_comments(target.read_text(encoding="utf-8")),
                state,
            )


def render():
    lib_text = _strip_comments((SRC / "lib.rs").read_text(encoding="utf-8"))
    state = {"modules": {}, "public": {("yamaa",)}, "files": {"lib.rs"}}
    state["allmods"] = []
    _discover(("yamaa",), lib_text, state)
    entries = []
    _parse_module(("yamaa",), lib_text, entries, state)
    actual = sorted(p.relative_to(SRC).as_posix() for p in SRC.rglob("*.rs"))
    expected = sorted(
        {p.relative_to(SRC).as_posix() for p in state["allmods"]} | state["files"]
    )
    if actual != expected:
        raise ValueError(f"facade module files changed: {actual!r} != {expected!r}")
    for entry in entries:
        if any(
            crate in entry
            for crate in ("yamaa_adapters", "yamaa_application", "yamaa_core")
        ):
            raise ValueError(f"facade surface references internals: {entry}")
    if not entries:
        raise ValueError("facade inventory is empty")
    return "\n".join(_HEADER + sorted(entries)) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    expected = render().encode("utf-8")
    if args.write:
        TARGET.write_bytes(expected)
    else:
        assert TARGET.read_bytes() == expected, (
            "facade API inventory differs from the `yamaa` facade sources; "
            "regenerate with tools/packaging/generate_facade_api.py --write"
        )
        print("PASS: facade API inventory matches the `yamaa` facade sources")


if __name__ == "__main__":
    main()
