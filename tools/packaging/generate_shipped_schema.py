"""Copy the schema files that the engine embeds; compare directly, without hashes.

The engine admits each 1.0 file type's closure and gives `schema(file_type)`
from the files themselves (#3030 section 2.12): every 1.0 schema module,
yaml/schema_*.yaml, and the JSON Schema of each 1.0 file type that
tools/packaging/generate_json_schema.py commits in yaml/json/. This copies
them byte for byte into the adapters crate's schema/ directory, each under
its path in yaml/, so that the crate, and the source packages that carry it
(tools/staging/engine_bundle.py), hold every byte that it embeds. The table
that it writes, src/shipped_schema/data.rs, names each copy with
`include_str!`, one line per file, and gives each file type's closure: its
entry module, then every module that it includes.

The default mode compares the table and each copy with yaml/, byte for byte,
and refuses a link in schema/ and a file there that copies nothing;
`--write` removes both and rewrites the table and the copies.
"""

import argparse
import os
from pathlib import Path

import yaml
from tools.paths import ROOT, WORKSPACE
from tools.validation._repository_yaml import UniqueKeyLoader

SOURCE = ROOT / "yaml"
CRATE = WORKSPACE / "crates/yamaa-adapters"
# The copies of the files that the crate embeds, each under its path in yaml/.
COPIES = CRATE / "schema"
TARGET = CRATE / "src/shipped_schema/data.rs"
# The entry module of each 1.0 file type (yaml/README.md).
V1_ENTRIES = {
    "spec": "schema_spec.yaml",
    "project": "schema_project.yaml",
    "codelists": "schema_codelists.yaml",
    "function": "schema_function.yaml",
}


def modules():
    """The names of the 1.0 schema modules, in name order."""
    return sorted(path.name for path in SOURCE.glob("schema_*.yaml"))


def json_schema(file_type):
    """The path in yaml/ of the committed JSON Schema of one 1.0 file type."""
    return f"json/{file_type}.schema.json"


def copied():
    """The path in yaml/ of each file that the crate embeds: every module, then
    each file type's JSON Schema."""
    return [*modules(), *(json_schema(file_type) for file_type in V1_ENTRIES)]


def entry(name, relative):
    """One table line: `name` and the copy of yaml/<relative>, as `include_str!`
    reads it from the table's own directory."""
    copies = Path(os.path.relpath(COPIES, TARGET.parent)).as_posix()
    return f'    ("{name}", include_str!("{copies}/{relative}")),'


def closure(entry):
    """A 1.0 file type's bundle: its entry module, then every module it includes."""
    found = []
    pending = [entry]
    while pending:
        name = pending.pop()
        if name in found:
            continue
        found.append(name)
        document = yaml.load(
            (SOURCE / name).read_text(encoding="ascii"), UniqueKeyLoader
        )
        pending.extend(document.get("includes", []))
    return [entry, *sorted(found[1:])]


def constant(name, kind, entries):
    """One `#[rustfmt::skip]` constant holding `entries`, a list of lines."""
    return [
        "#[rustfmt::skip]",
        f"pub(super) const {name}: &[{kind}] = &[",
        *entries,
        "];",
    ]


def render():
    """The table: each module and each JSON Schema by name, and each file
    type's closure, its entry module first."""
    lines = [
        "// Generated by tools/packaging/generate_shipped_schema.py --write.",
        "// The schema files that the package embeds: the copies in schema/ of",
        "// yaml/schema_*.yaml and of the JSON Schemas in yaml/json/, and each",
        "// file type's closure. Do not edit this table or the copies.",
    ]
    # The 1.0 schema: each module once, and each file type's closure by name.
    lines += constant(
        "V1_MODULES", "(&str, &str)", [entry(name, name) for name in modules()]
    )
    closures = []
    for file_type, name in V1_ENTRIES.items():
        names = ", ".join(f'"{module}"' for module in closure(name))
        closures.append(f'    ("{file_type}", &[{names}]),')
    lines += constant("V1_CLOSURES", "(&str, &[&str])", closures)
    # The JSON Schema of each file type, by type, as yaml/json/ commits it.
    lines += constant(
        "V1_JSON_SCHEMAS",
        "(&str, &str)",
        [entry(file_type, json_schema(file_type)) for file_type in V1_ENTRIES],
    )
    return "\n".join([*lines, ""])


def expected():
    """Each file that the generator writes, with the bytes it must hold: the
    table, then each copy, with the bytes of its file in yaml/."""
    files = {TARGET: render().encode("ascii")}
    for relative in copied():
        files[COPIES / relative] = (SOURCE / relative).read_bytes()
    return files


def links():
    """The links in schema/, schema/ itself included, in path order. A copy is
    a regular file, as the staging also requires (tools/staging/engine_bundle.py):
    a link would pass the comparison through to its target."""
    if COPIES.is_symlink():
        return [COPIES]
    if not COPIES.is_dir():
        return []
    return sorted(path for path in COPIES.rglob("*") if path.is_symlink())


def strays(files):
    """The regular files in schema/ that copy nothing, in path order."""
    if COPIES.is_symlink() or not COPIES.is_dir():
        return []
    return sorted(
        path
        for path in COPIES.rglob("*")
        if path.is_file() and not path.is_symlink() and path not in files
    )


def shown(path):
    """A path as the messages name it: from the repository root, when it is
    inside it."""
    return path.relative_to(ROOT).as_posix() if path.is_relative_to(ROOT) else path


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args(argv)
    files = expected()
    if args.write:
        # Links go first, so that nothing is written through one.
        for path in links():
            path.unlink()
        for path in strays(files):
            path.unlink()
        for path, payload in files.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(payload)
        return 0
    linked = links()
    errors = [f"ERROR: {shown(path)} is a link, not a copy" for path in linked]
    errors += [
        f"ERROR: regenerate {shown(path)}"
        for path, payload in files.items()
        if path not in linked and (not path.is_file() or path.read_bytes() != payload)
    ]
    errors += [f"ERROR: {shown(path)} copies no schema file" for path in strays(files)]
    for error in errors:
        print(error)
    if errors:
        print("Run: python -m tools.packaging.generate_shipped_schema --write")
        return 1
    print(
        "PASS: the shipped schema copies hold the bytes of the schema files and "
        "the committed JSON Schemas, and its table names each one"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
