"""Embed schema bytes in native packages; compare directly, without hashes.

The copy holds every schema module's exact bytes and, beside the 1.0 modules,
the JSON Schema of each 1.0 file type that tools/packaging/generate_json_schema.py
commits in yaml/v1/json/, byte for byte, which `schema(file_type)` gives
(#3030 section 2.12).
"""

import argparse

import yaml
from tools.paths import WORKSPACE
from tools.validation._repository_yaml import UniqueKeyLoader

SOURCE = WORKSPACE.parent / "yaml"
V1 = SOURCE / "v1"
TARGET = WORKSPACE / "crates/yamaa-adapters/src/shipped_schema/data.rs"
SEPARATE_ROOTS = {"schema_environment.yaml", "schema_project.yaml"}
# The entry module of each 1.0 file type (yaml/README.md).
V1_ENTRIES = {
    "spec": "schema_spec.yaml",
    "project": "schema_project.yaml",
    "codelists": "schema_codelists.yaml",
    "function": "schema_function.yaml",
}


def json_schema(file_type):
    """The committed JSON Schema of one 1.0 file type."""
    return V1 / "json" / f"{file_type}.schema.json"


def module_line(module, name=None):
    """One file's exact ASCII bytes as a raw string literal, named by `name`
    or else by the file's own name."""
    content = module.read_bytes().decode("ascii")
    # Raw strings preserve newlines and backslashes from the written source.
    delimiter = "#"
    while '"' + delimiter in content:
        delimiter += "#"
    return f'    ("{name or module.name}", r{delimiter}"{content}"{delimiter}),'


def closure(entry):
    """A 1.0 file type's bundle: its entry module, then every module it includes."""
    found = []
    pending = [entry]
    while pending:
        name = pending.pop()
        if name in found:
            continue
        found.append(name)
        document = yaml.load((V1 / name).read_text(encoding="ascii"), UniqueKeyLoader)
        pending.extend(document.get("includes", []))
    return [entry, *sorted(found[1:])]


def render():
    """Keep the entry first and preserve every module's exact UTF-8 bytes."""
    # Project and environment are separate roots. Shared bundle admission
    # rejects missing or unused modules, so closure drift fails native tests.
    modules = [SOURCE / "schema.yaml"] + sorted(
        p for p in SOURCE.glob("schema_*.yaml") if p.name not in SEPARATE_ROOTS
    )
    lines = [
        "// Generated by tools/packaging/generate_shipped_schema.py --write.",
        "// Authoritative sources: yaml/schema*.yaml, yaml/v1/schema_*.yaml and the",
        "// JSON Schemas in yaml/v1/json/.",
        "// Do not edit this copy.",
        "#[rustfmt::skip]",
        "pub(super) const MODULES: &[(&str, &str)] = &[",
    ]
    lines += [module_line(module) for module in modules]
    for constant, root in (
        ("PROJECT_MODULES", "schema_project.yaml"),
        ("ENVIRONMENT_MODULES", "schema_environment.yaml"),
    ):
        lines += [
            "];",
            "#[rustfmt::skip]",
            f"pub(super) const {constant}: &[(&str, &str)] = &[",
        ]
        lines += [
            module_line(module)
            for module in [SOURCE / root, SOURCE / "schema_shared.yaml"]
        ]
    # The 1.0 schema: each module once, and each file type's closure by name.
    lines += [
        "];",
        "#[rustfmt::skip]",
        "pub(super) const V1_MODULES: &[(&str, &str)] = &[",
    ]
    lines += [module_line(module) for module in sorted(V1.glob("schema_*.yaml"))]
    lines += [
        "];",
        "#[rustfmt::skip]",
        "pub(super) const V1_CLOSURES: &[(&str, &[&str])] = &[",
    ]
    for file_type, entry in V1_ENTRIES.items():
        names = ", ".join(f'"{name}"' for name in closure(entry))
        lines.append(f'    ("{file_type}", &[{names}]),')
    # The JSON Schema of each file type, by type, as yaml/v1/json/ commits it.
    lines += [
        "];",
        "#[rustfmt::skip]",
        "pub(super) const V1_JSON_SCHEMAS: &[(&str, &str)] = &[",
    ]
    lines += [
        module_line(json_schema(file_type), file_type) for file_type in V1_ENTRIES
    ]
    return "\n".join([*lines, "];", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    expected = render().encode("ascii")
    if args.write:
        TARGET.write_bytes(expected)
    else:
        assert TARGET.read_bytes() == expected, (
            "shipped schema differs from yaml/; regenerate with "
            "tools/packaging/generate_shipped_schema.py --write"
        )
        print(
            "PASS: shipped schema preserves the authoritative YAML bytes and the "
            "committed JSON Schemas"
        )


if __name__ == "__main__":
    main()
