"""Embed authoritative YAML bytes in native packages; compare directly, without hashes."""

import argparse

from tools.paths import WORKSPACE

SOURCE = WORKSPACE.parent / "yaml"
TARGET = WORKSPACE / "crates/yamaa-adapters/src/shipped_schema/data.rs"
SEPARATE_ROOTS = {
    "schema_define.yaml",
    "schema_environment.yaml",
    "schema_project.yaml",
}


def render():
    """Keep the entry first and preserve every module's exact UTF-8 bytes."""
    # Project, environment and submission are separate roots. Shared bundle
    # admission rejects missing or unused modules, so closure drift fails
    # native tests.
    modules = [SOURCE / "schema.yaml"] + sorted(
        p for p in SOURCE.glob("schema_*.yaml") if p.name not in SEPARATE_ROOTS
    )
    lines = [
        "// Generated by tools/packaging/generate_shipped_schema.py --write.",
        "// Authoritative sources: yaml/schema*.yaml. Do not edit this copy.",
        "#[rustfmt::skip]",
        "pub(super) const MODULES: &[(&str, &str)] = &[",
    ]
    for module in modules:
        content = module.read_bytes().decode("ascii")
        # Raw strings preserve newlines and backslashes from the written source.
        delimiter = "#"
        while '"' + delimiter in content:
            delimiter += "#"
        lines.append(f'    ("{module.name}", r{delimiter}"{content}"{delimiter}),')
    for constant, root in (
        ("PROJECT_MODULES", "schema_project.yaml"),
        ("ENVIRONMENT_MODULES", "schema_environment.yaml"),
    ):
        lines += [
            "];",
            "#[rustfmt::skip]",
            f"pub(super) const {constant}: &[(&str, &str)] = &[",
        ]
        for module in [SOURCE / root, SOURCE / "schema_shared.yaml"]:
            content = module.read_bytes().decode("ascii")
            delimiter = "#"
            while '"' + delimiter in content:
                delimiter += "#"
            lines.append(f'    ("{module.name}", r{delimiter}"{content}"{delimiter}),')
    return "\n".join([*lines, "];", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    expected = render().encode("ascii")
    if args.write:
        TARGET.write_bytes(expected)
    else:
        assert TARGET.read_bytes() == expected, (
            "shipped schema differs from authoritative YAML"
        )
        print("PASS: shipped schema preserves authoritative YAML bytes")


if __name__ == "__main__":
    main()
