"""Report the size of the Rust workspace, crate by crate.

    uv run --project python --no-sync python -m tools.validation.source_size

prints a Markdown table with a row for each crate under `rust/crates/`: its
lines of source, test and generated code, and how many of its functions are
over 250 lines. The planning issue's board comment carries it; measurements
go in issues, never in committed files (#3797). This is a report, not a
check: `tools.validation.check_source_size` holds the file ceiling.

- A file is generated when one of its first five lines starts with
  `// Generated by`, as each generator under `tools/packaging/` writes it.
  All its lines are generated.
- A test line belongs to the crate's `tests/` directory, to a module of
  `src/` that only tests load, or to an item that `#[cfg(test)]`, or `test`
  inside `#[cfg(all(...))]`, compiles for tests only, found as
  `tools.validation.check_diagnostics` finds them.
- A source line is any other: `src/` outside its tests, the examples and the
  build scripts.
- A function's length is the count Clippy's `too_many_lines` makes: the lines
  of its body that hold code, without its blank and comment-only lines. Test
  functions count too, since Clippy lints every target.
"""

import argparse
import re
import sys
from collections import Counter
from pathlib import Path

from tools.paths import ROOT
from tools.validation.check_diagnostics import (
    RUST_NAME,
    balanced,
    blank,
    cfg_test_items,
    json_test_sources,
    rust_tokens,
)

CRATES = Path("rust/crates")
GENERATED = "// Generated by "
HEADER_LINES = 5
FUNCTION_CEILING = 250
FUNCTION = re.compile(rf"\bfn\s+{RUST_NAME}")
COLUMNS = ("source", "test", "generated", "functions")


def line_count(text):
    """The lines of a text, counting a last line that has no newline."""
    return text.count("\n") + (bool(text) and not text.endswith("\n"))


def is_generated(text):
    """Whether one of a Rust file's first lines says that a generator writes it."""
    return any(
        line.startswith(GENERATED)
        for line in text.split("\n", HEADER_LINES)[:HEADER_LINES]
    )


def rust_files(root):
    """Every Rust file under `rust/crates/`, as ``(crate, path, text)``."""
    for path in sorted((root / CRATES).rglob("*.rs")):
        crate = path.relative_to(root / CRATES).parts[0]
        yield crate, path, path.read_text(encoding="utf-8")


def place(root, path):
    """The directory of its crate that a Rust file is in, such as `src` or
    `tests`, or None for a file at the top of its crate."""
    parts = path.relative_to(root / CRATES).parts
    return parts[1] if len(parts) > 2 else None


def body_start(code, offset):
    """Where the body of the function whose signature continues at ``offset``
    opens, or None for a function declared without a body."""
    depth = 0
    for index in range(offset, len(code)):
        character = code[index]
        if character in "([":
            depth += 1
        elif character in ")]":
            depth -= 1
        elif character in ";{" and not depth:
            return index if character == "{" else None
    return None


def function_lengths(text, tokens, code):
    """The length of each function with a body, as Clippy counts it. ``code``
    is ``text`` with the ``tokens`` of its comments and literals spaced out."""
    visible = blank(text, tokens, {"comment"})
    lengths = []
    for match in FUNCTION.finditer(code):
        start = body_start(code, match.end())
        end = None if start is None else balanced(code, start, "{", "}")
        if end is not None:
            body = visible[start + 1 : end - 1].strip().split("\n")
            lengths.append(sum(1 for line in body if line.strip()))
    return lengths


def measure(root):
    """Each crate's lines of source, test and generated code and its number
    of functions over the ceiling, by crate name."""
    files = list(rust_files(root))
    only_tests = json_test_sources(
        {path.resolve(): text for _, path, text in files if place(root, path) == "src"}
    )
    crates = {}
    for crate, path, text in files:
        counts = crates.setdefault(crate, Counter())
        tokens = list(rust_tokens(text))
        code = blank(text, tokens, {"comment", "character", "string"})
        lines = line_count(text)
        if is_generated(text):
            counts["generated"] += lines
        elif place(root, path) == "tests" or path.resolve() in only_tests:
            counts["test"] += lines
        else:
            tests = sum(
                code.count("\n", low, high) + 1 for low, high in cfg_test_items(code)
            )
            counts["test"] += tests
            counts["source"] += lines - tests
        counts["functions"] += sum(
            length > FUNCTION_CEILING for length in function_lengths(text, tokens, code)
        )
    return crates


def table(crates):
    """The Markdown table of the measured crates and their total."""
    rows = [
        (
            "Crate",
            "Source",
            "Test",
            "Generated",
            f"Functions over {FUNCTION_CEILING} lines",
        ),
        ("---", "---:", "---:", "---:", "---:"),
    ]
    total = Counter()
    for crate, counts in sorted(crates.items()):
        total.update(counts)
        rows.append((crate, *(f"{counts[column]:,}" for column in COLUMNS)))
    rows.append(("Total", *(f"{total[column]:,}" for column in COLUMNS)))
    return "\n".join("| " + " | ".join(row) + " |" for row in rows)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    crates = measure(parser.parse_args(argv).root)
    if not crates:
        print(f"ERROR: {CRATES.as_posix()}: no Rust files found")
        return 1
    print(table(crates))
    return 0


if __name__ == "__main__":
    sys.exit(main())
