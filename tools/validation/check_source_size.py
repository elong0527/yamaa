"""Check the 3,000-line ceiling of a hand-written Rust file.

A source or test file splits by feature before it passes 3,000 lines (#2413,
the size ceiling of #3797). Every `.rs` file under `rust/crates/` is held to
the ceiling, a test file as much as a source file. A generated file is
exempt: one of its first five lines starts with
`// Generated by tools/packaging/<name>.py`, as each generator writes it
(`tools.validation.source_size`). A marker that names no script there fails,
so a file cannot leave the ceiling by saying so.

A hand-written file over the ceiling passes only while ALLOWLIST names the
issue that brings it under. That entry fails once the issue is closed, and
once its file is gone, generated or within the ceiling, so the split that
the issue makes removes the entry too. An issue's state is GitHub's, and a
repository check reads no network: the caller states the issues it knows to
be closed with `--closed`. `make check-repository` passes none; the
orchestrator's board run passes the allowlisted issues that GitHub reports
closed (#3806).
"""

import argparse
import sys
from pathlib import Path

from tools.paths import ROOT
from tools.validation.source_size import (
    CRATES,
    GENERATORS,
    generator,
    is_generated,
    is_generator,
    line_count,
    rust_files,
)

CEILING = 3000
# Each hand-written file over the ceiling, and the open issue that splits it.
ALLOWLIST = {}
HINT = (
    "Split a file over the ceiling by feature, as tests/<area>.rs files split "
    "by family (#2413); until then, an ALLOWLIST entry in "
    "tools/validation/check_source_size.py names the open issue that splits it. "
    "A generated file is exempt: one of its first five lines names the script "
    "that writes it, `// Generated by tools/packaging/<name>.py`."
)


def check(root, allowlist, closed=frozenset()):
    """Every hand-written Rust file under `root` over the ceiling that
    `allowlist` does not name, and every entry of `allowlist` that no longer
    holds. `closed` holds the numbers of the issues known to be closed."""
    root = Path(root)
    files = {path.relative_to(root): text for _, path, text in rust_files(root)}
    if not files:
        return [f"{CRATES.as_posix()}: no Rust files found"]
    errors = []
    over = set()
    for relative, text in files.items():
        name = generator(text)
        if name is not None and not is_generator(root, name):
            errors.append(
                f"{relative.as_posix()}: `// Generated by {name}` names no script "
                f"under {GENERATORS.as_posix()}/"
            )
        if not is_generated(root, text) and (lines := line_count(text)) > CEILING:
            over.add(relative)
            if relative not in allowlist:
                errors.append(
                    f"{relative.as_posix()}: {lines:,} lines, "
                    f"over the {CEILING:,}-line ceiling"
                )
    for relative, issue in sorted(allowlist.items()):
        entry = f"{relative.as_posix()}: allowed over the ceiling until #{issue}"
        if relative not in files:
            errors.append(f"{entry}, but the file is gone; remove its entry")
        elif is_generated(root, files[relative]):
            errors.append(f"{entry}, but the file is generated; remove its entry")
        elif relative not in over:
            lines = line_count(files[relative])
            errors.append(f"{entry}, but it has {lines:,} lines; remove its entry")
        elif issue in closed:
            errors.append(
                f"{entry}, and #{issue} is closed; split the file, "
                "or name the open issue that will"
            )
    return errors


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument(
        "--closed",
        type=int,
        nargs="*",
        default=[],
        metavar="ISSUE",
        help="the issues known to be closed; an ALLOWLIST entry naming one fails",
    )
    args = parser.parse_args(argv)
    errors = check(args.root, ALLOWLIST, frozenset(args.closed))
    for error in errors:
        print(f"ERROR: {error}")
    if errors:
        print(HINT)
        return 1
    allowed = ", ".join(
        f"{path.as_posix()} until #{issue}" for path, issue in sorted(ALLOWLIST.items())
    )
    print(
        f"PASS: no hand-written Rust file under {CRATES.as_posix()}/ is over "
        f"{CEILING:,} lines" + (f", but the allowlisted {allowed}." if allowed else ".")
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
