"""Render the benchmark README index from case READMEs and public entries."""

import argparse
import re
import sys
from pathlib import Path

from tools.benchmark import LIFECYCLES, load_metadata
from tools.conformance.public_conformance import plan
from tools.paths import ROOT


def render_index(fixtures, current):
    headings = list(
        re.finditer(r"^[ \t]*##[ \t]+Benchmarks[^\n]*(?:\n|$)", current, re.MULTILINE)
    )
    if len(headings) != 1 or headings[0].group() != "## Benchmarks\n":
        raise ValueError("benchmark index requires exactly one '## Benchmarks' heading")
    prefix = current[: headings[0].start()]
    payload = plan(fixtures)
    active = sum(not row["excluded"] for row in payload["examples"])
    lines = [
        "## Benchmarks",
        "",
        "<!-- Generated by tools/benchmark_docs/build_index.py. -->",
        "",
        f"{len(payload['examples'])} authored cases; {active} active cases use the same public",
        "Python and R plan. Host entries describe runnable metadata. Actual passing",
        "coverage is gated by the native run: every active benchmark must pass on every lane.",
        "",
        "| Benchmark | Derives | Lifecycle | Public conformance |",
        "|---|---|---|---|",
    ]
    for row in payload["examples"]:
        name = row["name"]
        readme = (fixtures / name / "README.md").read_text(encoding="utf-8")
        title = re.search(r"^# (.+)$", readme, re.MULTILINE)
        lifecycle = load_metadata(fixtures / name)["lifecycle"]
        if title is None:
            raise ValueError(f"missing title: {name}")
        badge = (
            f"[![Lifecycle: {lifecycle}](https://img.shields.io/badge/Lifecycle-{lifecycle}-{LIFECYCLES[lifecycle]})]"
            "(https://github.com/elong0527/yamaa/blob/main/benchmarks/README.md#lifecycle)"
        )
        description = title.group(1).replace("|", "\\|")
        coverage = f"Excluded: {row['excluded']}" if row["excluded"] else "Python, R"
        lines.append(f"| [`{name}`]({name}/) | {description} | {badge} | {coverage} |")
    return prefix + "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument(
        "--output",
        type=Path,
        help="write the rendered README here instead of to standard output",
    )
    args = parser.parse_args()
    path = args.root / "benchmarks/README.md"
    try:
        result = render_index(path.parent, path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        print(f"Cannot generate benchmark index: {error}", file=sys.stderr)
        return 1
    # The committed README keeps only its heading and prose, so the rendered
    # index is never written back in place.
    if args.output is None:
        sys.stdout.write(result)
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(result, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
