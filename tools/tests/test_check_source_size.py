"""The 3,000-line ceiling of a hand-written Rust, Python or R file: a file
over it fails, a generated file is exempt when its marker names an existing
generator, and an allowlist entry holds only while its issue is open and its
file is still over the ceiling."""

import tempfile
import unittest
from pathlib import Path
from unittest import mock

from tools.commands import repository
from tools.tests.support import run_main, write
from tools.validation import check_source_size as size

SOURCE = Path("rust/crates/yamaa-core/src/big.rs")
TEST = Path("rust/crates/yamaa-adapters/tests/big.rs")
OTHER = Path("rust/crates/yamaa/src/lib.rs")
GENERATOR = Path("tools/packaging/generate_big.py")
MARKER = "// Generated by tools/packaging/generate_big.py --write. Do not edit.\n"
OVER = f"{SOURCE.as_posix()}: 3,001 lines, over the 3,000-line ceiling"
ENTRY = f"{SOURCE.as_posix()}: allowed over the ceiling until #3799"


def unnamed(generator):
    """The check's finding on SOURCE when its marker names `generator`, which
    is no script under tools/packaging/."""
    return (
        f"{SOURCE.as_posix()}: `// Generated by {generator}` names no script "
        "under tools/packaging/"
    )


def rust(lines, first=""):
    """Rust text of exactly `lines` lines, which open with `first`."""
    return first + "// line\n" * (lines - first.count("\n"))


def script(lines, first=""):
    """Python or R text of exactly `lines` lines, which open with `first`."""
    return first + "# line\n" * (lines - first.count("\n"))


def over(path):
    """The check's finding on `path` at 3,001 lines."""
    return f"{path.as_posix()}: 3,001 lines, over the 3,000-line ceiling"


class FileCeiling(unittest.TestCase):
    def setUp(self):
        directory = tempfile.TemporaryDirectory(prefix="yamaa-source-size-")
        self.addCleanup(directory.cleanup)
        self.directory = directory.name

    def tree(self, files):
        """A fresh repository root that holds `files`, a path to its text
        each, beside one small file of another crate and the generator that
        MARKER names."""
        root = Path(tempfile.mkdtemp(dir=self.directory))
        for path, text in {OTHER: rust(10), GENERATOR: "", **files}.items():
            write(root, path, text)
        return root

    def test_a_file_over_the_ceiling_fails_unless_it_is_generated(self):
        cases = (
            ("a source file of 3,001 lines", SOURCE, rust(3001), [OVER]),
            (
                "a test file of 3,001 lines",
                TEST,
                rust(3001),
                [f"{TEST.as_posix()}: 3,001 lines, over the 3,000-line ceiling"],
            ),
            ("a file of 3,000 lines", SOURCE, rust(3000), []),
            ("the marker on the first line", SOURCE, rust(3001, MARKER), []),
            (
                "the marker on the fifth line",
                SOURCE,
                rust(3001, "//!\n" * 4 + MARKER),
                [],
            ),
            (
                "the marker on the sixth line",
                SOURCE,
                rust(3001, "//!\n" * 5 + MARKER),
                [OVER],
            ),
            (
                "the marker naming a generator that does not exist",
                SOURCE,
                rust(3001, "// Generated by tools/packaging/generate_gone.py\n"),
                [unnamed("tools/packaging/generate_gone.py"), OVER],
            ),
            (
                "the marker naming a script outside tools/packaging/",
                SOURCE,
                rust(3001, "// Generated by tools/generate_big.py --write.\n"),
                [unnamed("tools/generate_big.py"), OVER],
            ),
            (
                "a file within the ceiling whose marker names no generator",
                SOURCE,
                rust(10, "// Generated by hand. Do not edit.\n"),
                [unnamed("hand.")],
            ),
            (
                "a doc comment that starts with the marker's words",
                SOURCE,
                rust(
                    3001, "//! Generated by `generate_bindings.py`, a host calls it.\n"
                ),
                [OVER],
            ),
        )
        for label, path, text, expected in cases:
            with self.subTest(case=label):
                self.assertEqual(
                    size.check(self.tree({path: text}), {}), expected, label
                )

    def test_a_python_or_r_file_over_the_ceiling_fails_unless_it_is_generated(self):
        installed = Path("python/tests/installed/installed_big.py")
        suite = Path("R/yamaa/tests/big.R")
        python_marker = "# Generated by tools/packaging/generate_big.py --write.\n"
        cases = (
            ("an installed Python suite", installed, script(3001), [over(installed)]),
            (
                "a Python source file",
                Path("python/src/yamaa/big.py"),
                script(3001),
                [over(Path("python/src/yamaa/big.py"))],
            ),
            (
                "a tools test file",
                Path("tools/tests/test_big.py"),
                script(3001),
                [over(Path("tools/tests/test_big.py"))],
            ),
            ("an R test file", suite, script(3001), [over(suite)]),
            (
                "an R source file",
                Path("R/yamaa/R/big.R"),
                script(3001),
                [over(Path("R/yamaa/R/big.R"))],
            ),
            ("a Python file of 3,000 lines", installed, script(3000), []),
            (
                "a Python file with its marker",
                installed,
                script(3001, python_marker),
                [],
            ),
            ("an R file with its marker", suite, script(3001, python_marker), []),
            (
                "a Python file with Rust's marker",
                installed,
                script(3001, MARKER),
                [over(installed)],
            ),
            (
                "a Python marker naming no generator",
                installed,
                script(10, "# Generated by hand.\n"),
                [
                    f"{installed.as_posix()}: `# Generated by hand.` names no "
                    "script under tools/packaging/"
                ],
            ),
            (
                "a file of a hidden directory inside a walked one",
                Path("tools/.cache/big.py"),
                script(3001),
                [],
            ),
            ("a file of a cache", Path("tools/__pycache__/big.py"), script(3001), []),
            (
                "a Python file outside the walked directories",
                Path("evaluations/big.py"),
                script(3001),
                [],
            ),
        )
        for label, path, text, expected in cases:
            with self.subTest(case=label):
                self.assertEqual(
                    size.check(self.tree({path: text}), {}), expected, label
                )

    def test_an_entry_holds_only_while_its_issue_is_open(self):
        root = self.tree({SOURCE: rust(3001)})
        cases = (
            ("no issue closed", set(), []),
            ("another issue closed", {3800}, []),
            (
                "its issue closed",
                {3799, 3800},
                [
                    f"{ENTRY}, and #3799 is closed; split the file, "
                    "or name the open issue that will"
                ],
            ),
        )
        for label, closed, expected in cases:
            with self.subTest(case=label):
                self.assertEqual(
                    size.check(root, {SOURCE: 3799}, closed), expected, label
                )

    def test_an_entry_fails_once_its_file_is_no_longer_over_the_ceiling(self):
        cases = (
            (
                "the file within the ceiling",
                {SOURCE: rust(3000)},
                f"{ENTRY}, but it has 3,000 lines; remove its entry",
            ),
            ("the file gone", {}, f"{ENTRY}, but the file is gone; remove its entry"),
            (
                "the file generated",
                {SOURCE: rust(3001, MARKER)},
                f"{ENTRY}, but the file is generated; remove its entry",
            ),
        )
        for label, files, expected in cases:
            with self.subTest(case=label):
                self.assertEqual(
                    size.check(self.tree(files), {SOURCE: 3799}), [expected], label
                )

    def test_a_tree_without_rust_files_fails(self):
        self.assertEqual(
            size.check(Path(self.directory), {}),
            ["rust/crates: no Rust files found"],
        )

    def test_main_fails_an_entry_whose_issue_it_is_told_is_closed(self):
        root = self.tree({SOURCE: rust(3001)})
        passed = (
            "PASS: no hand-written Rust, Python or R file is over 3,000 lines, "
            f"but the allowlisted {SOURCE.as_posix()} until #3799.\n"
        )
        failed = (
            f"ERROR: {ENTRY}, and #3799 is closed; split the file, "
            f"or name the open issue that will\n{size.HINT}\n"
        )
        cases = (
            ("no closed issue stated", (), (0, passed, "")),
            ("its issue stated closed", ("--closed", "3712", "3799"), (1, failed, "")),
        )
        for label, closed, expected in cases:
            with self.subTest(case=label):
                with mock.patch.object(size, "ALLOWLIST", {SOURCE: 3799}):
                    result = run_main(size.main, "--root", str(root), *closed)
                self.assertEqual(result, expected, label)

    def test_the_repository_check_runs_it(self):
        self.assertIn("tools.validation.check_source_size", repository.CHECKS)


if __name__ == "__main__":
    unittest.main()
