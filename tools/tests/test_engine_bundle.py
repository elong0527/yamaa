    def test_the_archive_is_maturin_output_with_crates_listed_outside_the_stage(self):
        calls = []
        project = tomllib.loads((ROOT / "python/pyproject.toml").read_text())
        name = f"yamaa-{project['project']['version']}.tar.gz"

        def run(command, **options):
            calls.append((command, options))
            if command[1:] == ["--version"]:
                return subprocess.CompletedProcess(command, 0, stdout=version)
            Path(command[-1], name).write_bytes(b"archive")
            return subprocess.CompletedProcess(command, 0)

        with (
            tempfile.TemporaryDirectory() as directory,
            mock.patch.object(bundle, "stage", lambda host, root: root.mkdir()),
            mock.patch.object(bundle, "python_project", lambda root: None),
            mock.patch.object(bundle.subprocess, "run", run),
        ):
            output = Path(directory) / "dist"
            version = "maturin 1.9.5\n"
            with self.assertRaisesRegex(ValueError, "maturin 1.9.5 is not the"):
                bundle.python_archive(output)
            self.assertFalse(output.exists())
            version = "maturin 1.9.6\n"
            archive = bundle.python_archive(output)
            self.assertEqual(archive, output / name)
            command, options = calls[-1]
            self.assertEqual(command[:2], ["maturin", "sdist"])
            # `cargo package --list` creates no target directory in the stage.
            target = Path(options["env"]["CARGO_TARGET_DIR"])
            self.assertFalse(target.is_relative_to(options["cwd"]))
            # A second build never overwrites the first archive.
            with self.assertRaises(FileExistsError):
                bundle.python_archive(output)


