def lock(*packages, version=4):
    """A Cargo lock of (name, version, registry?, dependencies) packages."""
    lines = [
        "# This file is automatically @generated by Cargo.",
        f"version = {version}",
    ]
    for name, number, registry, dependencies in packages:
        lines += ["", "[[package]]", f'name = "{name}"', f'version = "{number}"']
        if registry:
            lines += [f'source = "{REGISTRY}"', f'checksum = "recorded {name}"']
        if dependencies:
            lines += ["dependencies = ["] + [f' "{entry}",' for entry in dependencies]
            lines.append("]")
    return "\n".join(lines) + "\n"


CORE = ("core", "0.5.0", False, ["parser 1.0.0"])
PYTHON = ("python-binding", "0.5.0", False, ["core", "pyo3"])
R = ("r-binding", "0.5.0", False, ["core", "extendr"])
PARSER_1 = ("parser", "1.0.0", True, [])
PARSER_2 = ("parser", "2.0.0", True, [])
PYO3 = ("pyo3", "0.27.2", True, ["parser 2.0.0"])
EXTENDR = ("extendr", "0.9.0", True, ["parser 2.0.0", "lazy"])
LAZY = ("lazy", "1.5.1", True, [])
CANONICAL = lock(CORE, PYTHON, R, PARSER_1, PARSER_2, PYO3, EXTENDR, LAZY)
ROOTS = ("core", "python-binding")


class LockTests(unittest.TestCase):
    def test_the_members_closure_of_canonical_entries_is_kept(self):
        trimmed = lock(CORE, PYTHON, PARSER_1, PARSER_2, PYO3)
        kept = bundle.verify_lock(trimmed, CANONICAL, ROOTS)
        self.assertEqual(
            sorted((name, version) for name, version, _ in kept),
            [
                ("core", "0.5.0"),
                ("parser", "1.0.0"),
                ("parser", "2.0.0"),
                ("pyo3", "0.27.2"),
                ("python-binding", "0.5.0"),
            ],
        )

    def test_entries_that_are_no_longer_ambiguous_resolve(self):
        # Cargo drops the version from an entry once one version remains.
        canonical = lock(
            ("a", "0.1.0", False, ["b 1.0.0"]),
            ("c", "0.1.0", False, ["b 2.0.0"]),
            ("b", "1.0.0", True, []),
            ("b", "2.0.0", True, []),
        )
        trimmed = lock(("a", "0.1.0", False, ["b"]), ("b", "1.0.0", True, []))
        self.assertEqual(len(bundle.verify_lock(trimmed, canonical, ("a",))), 2)
        moved = lock(("a", "0.1.0", False, ["b"]), ("b", "2.0.0", True, []))
        with self.assertRaisesRegex(ValueError, "depends on b 2.0.0, which the"):
            bundle.verify_lock(moved, canonical, ("a",))

    def test_changed_entries_refuse(self):
        trimmed = lock(CORE, PYTHON, PARSER_1, PARSER_2, PYO3)
        for old, new, message in (
            ('version = "0.27.2"', 'version = "0.27.3"', "pyo3 0.27.3 differs"),
            ('"recorded pyo3"', '"another pyo3"', "pyo3 0.27.2 differs"),
            (f'source = "{REGISTRY}"\nchecksum = "recorded pyo3"', "", "pyo3 0.27.2"),
        ):
            with self.subTest(new=new), self.assertRaisesRegex(ValueError, message):
                bundle.verify_lock(trimmed.replace(old, new), CANONICAL, ROOTS)

    def test_unrecorded_dependencies_and_unreached_packages_refuse(self):
        unrecorded = lock(
            CORE,
            PYTHON,
            PARSER_1,
            PARSER_2,
            (*PYO3[:3], ["parser 2.0.0", "lazy"]),
            LAZY,
        )
        with self.assertRaisesRegex(ValueError, "depends on lazy 1.5.1, which the"):
            bundle.verify_lock(unrecorded, CANONICAL, ROOTS)
        # The canonical lock itself keeps the R binding's crates.
        with self.assertRaisesRegex(ValueError, "extendr 0.9.0 is outside the"):
            bundle.verify_lock(CANONICAL, CANONICAL, ROOTS)

    def test_missing_members_and_malformed_locks_refuse(self):
        for trimmed, message in (
            (lock(CORE, PARSER_1), "bundle member python-binding is not locked"),
            (lock(CORE, PYTHON, PARSER_1, PARSER_2, PYO3, version=3), "lock format"),
            (lock(CORE, PYTHON, PARSER_1, PARSER_1, PARSER_2, PYO3), "locked twice"),
            (
                lock(CORE, (*PYTHON[:3], ["core", "parser"]), PARSER_1, PARSER_2, PYO3),
                "names the dependency parser, which matches no single",
            ),
        ):
            with self.subTest(message=message):
                with self.assertRaisesRegex(ValueError, message):
                    bundle.verify_lock(trimmed, CANONICAL, ROOTS)


