class VendoredSourceTests(unittest.TestCase):
    def vendored(self, root):
        workspace = root / "rust"
        package = workspace / "vendor/witness"
        for name, payload in {
            "Cargo.toml": b'[package]\nname = "witness"\nversion = "0.1.0"\n',
            "src/lib.rs": b"pub fn witness() {}\n",
            "LICENSE": b"two upstream authors\n",
            "LICENSES/first-MIT": b"first notice\n",
            "LICENSES/second-MIT": b"second notice\n",
            "README.md": b"released readme\n",
            "PROVENANCE.md": b"release plus narrow source patch\n",
            "compact-flow-pairs.patch": b"independent source patch\n",
        }.items():
            (package / name).parent.mkdir(parents=True, exist_ok=True)
            (package / name).write_bytes(payload)
        (workspace / "Cargo.toml").write_text("[workspace]\nmembers = []\n")
        return workspace, package

    def test_any_workspace_patch_refuses(self):
        # A [patch] applies only when this workspace is the root, so a project
        # that embeds the facade would build without it (#2929).
        for manifest in (
            '[patch.crates-io]\nwitness = {path = "vendor/witness"}\n',
            '[patch."https://example.invalid/witness"]\nwitness = {path = "x"}\n',
            "patch = 42\n",
            "[patch]\ncrates-io = 'witness'\n",
        ):
            with self.subTest(manifest=manifest), tempfile.TemporaryDirectory() as d:
                workspace = Path(d)
                (workspace / "Cargo.toml").write_text(
                    manifest + "[workspace]\nmembers = []\n"
                )
                with self.assertRaisesRegex(ValueError, r"must not declare \[patch\]"):
                    list(bundle.vendored_sources(workspace))

    def test_only_complete_regular_crate_directories_are_admitted(self):
        with tempfile.TemporaryDirectory() as directory:
            workspace, package = self.vendored(Path(directory))
            self.assertEqual(len(list(bundle.vendored_sources(workspace))), 8)
            stray = workspace / "vendor/notes.txt"
            stray.write_bytes(b"not a crate\n")
            with self.assertRaisesRegex(ValueError, "invalid vendored crate directory"):
                list(bundle.vendored_sources(workspace))
            stray.unlink()
            junk = package / "target/junk.rs"
            junk.parent.mkdir()
            junk.write_bytes(b"fn junk() {}\n")
            with self.assertRaisesRegex(ValueError, "build or cache files"):
                list(bundle.vendored_sources(workspace))
            shutil.rmtree(junk.parent)
            (package / "PROVENANCE.md").unlink()
            with self.assertRaisesRegex(ValueError, "missing PROVENANCE.md"):
                list(bundle.vendored_sources(workspace))

    def test_ancestor_build_or_cache_names_are_not_refused(self):
        for ancestor in ("target", ".git", "__pycache__"):
            with self.subTest(ancestor=ancestor), tempfile.TemporaryDirectory() as d:
                root = Path(d) / ancestor / "checkout"
                root.mkdir(parents=True)
                workspace, _ = self.vendored(root)
                self.assertEqual(len(list(bundle.vendored_sources(workspace))), 8)

    def test_links_refuse(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            workspace, package = self.vendored(root)
            notice = package / "LICENSES/second-MIT"
            notice.unlink()
            try:
                notice.symlink_to(package / "LICENSES/first-MIT")
            except OSError as error:
                self.skipTest(f"symlinks are unavailable: {error}")
            with self.assertRaisesRegex(ValueError, "must not be symlinks"):
                list(bundle.vendored_sources(workspace))
            notice.unlink()
            notice.write_bytes(b"second notice\n")
            # A linked crate or vendor directory could ship outside sources.
            shutil.copytree(package, root / "outside")
            (workspace / "vendor/linked").symlink_to(root / "outside")
            with self.assertRaisesRegex(ValueError, "must not be symlinks"):
                list(bundle.vendored_sources(workspace))
            (workspace / "vendor/linked").unlink()
            (workspace / "vendor").rename(root / "vendor")
            (workspace / "vendor").symlink_to(root / "vendor", target_is_directory=True)
            with self.assertRaisesRegex(ValueError, "must not be symlinks"):
                list(bundle.vendored_sources(workspace))


class StagingTests(unittest.TestCase):
    @unittest.skipUnless(shutil.which("cargo"), "cargo is unavailable")
    def test_each_host_workspace_trims_the_canonical_lock(self):
        with tempfile.TemporaryDirectory() as directory:
            for host, kept_crate, dropped_crate in (
                ("python", "pyo3", "extendr-api"),
                ("r", "extendr-api", "pyo3"),
            ):
                with self.subTest(host=host):
                    destination = Path(directory) / host
                    kept = bundle.stage_workspace(host, destination)
                    names = {name for name, _, _ in kept}
                    self.assertIn(kept_crate, names)
                    self.assertNotIn(dropped_crate, names)
                    # The adapters' test-only oracle stays out of every bundle.
                    self.assertNotIn("parquet", names)
                    for manifest in (destination / "crates").glob("*/Cargo.toml"):
                        self.assertNotIn(
                            "dev-dependencies", tomllib.loads(manifest.read_text())
                        )
                    self.assertEqual(
                        bundle.verify_lock(
                            (destination / "Cargo.lock").read_text(),
                            (WORKSPACE / "Cargo.lock").read_text(),
                            bundle.members(host),
                        ),
                        kept,
                    )
                    self.assertEqual(
                        sorted(
                            path.name for path in (destination / "crates").iterdir()
                        ),
                        sorted(bundle.members(host)),
                    )
                    self.assertEqual(list(destination.rglob("tests")), [])
                    self.assertEqual(list(destination.rglob("rust-toolchain*")), [])
                    # The facade's build reads the selftest cases from its
                    # own crate, never from a benchmarks/ beside the bundle.
                    for relative, path in selftest_cases.case_files():
                        self.assertEqual(
                            (destination / SELFTEST / relative).read_bytes(),
                            path.read_bytes(),
                        )
                    self.assertFalse((destination.parent / "benchmarks").exists())

    def test_an_existing_destination_is_preserved(self):
        with tempfile.TemporaryDirectory() as directory:
            marker = Path(directory) / "keep.txt"
            marker.write_text("prior build")
            with self.assertRaises(FileExistsError):
                bundle.stage("python", Path(directory))
            self.assertEqual(marker.read_text(), "prior build")

    def test_the_python_project_points_maturin_at_the_bundle(self):
        with tempfile.TemporaryDirectory() as directory:
            destination = Path(directory) / "stage"
            destination.mkdir()
            bundle.python_project(destination)
            pyproject = tomllib.loads((destination / "pyproject.toml").read_text())
            self.assertEqual(pyproject["build-system"]["build-backend"], "maturin")
            maturin = pyproject["tool"]["maturin"]
            self.assertEqual(
                maturin["manifest-path"], "rust/crates/yamaa-python/Cargo.toml"
            )
            self.assertIn(
                {"path": ".cargo/config.toml", "format": "sdist"}, maturin["include"]
            )
            self.assertIn(
                {"path": "vendor/**/*", "format": "sdist"}, maturin["include"]
            )
            # pip builds the wheel with the native wheels' profile, which the
            # bundle's manifest carries: release without the symbol table.
            # Panics still unwind, as the Parquet reader's containment needs.
            profiles = tomllib.loads(bundle.workspace_manifest("python"))["profile"]
