"""The size report of the Rust workspace: each crate's lines of source, test
and generated code, and its functions over 250 lines as Clippy counts them."""

import tempfile
import unittest
from pathlib import Path

from tools.tests.support import run_main, write
from tools.validation import source_size

# 14 lines: lines 5-6 and 8-14 are the two items compiled for tests only.
LIB = """\
pub fn small() -> u8 {
    1
}

#[cfg(test)]
mod checks;

#[cfg(test)]
mod tests {
    #[test]
    fn small_is_one() {
        assert_eq!(super::small(), 1);
    }
}
"""
# The module that only tests load, 4 lines.
CHECKS = """\
#[test]
fn checks_run() {
    assert!(true);
}
"""
STATEMENT = "    let _ = 0;\n"
# 253 lines, a body of 251 code lines; then 254 lines, a body of 250 code
# lines beside a comment and a blank line, which Clippy does not count.
LONG = (
    "pub fn over() {\n"
    + STATEMENT * 251
    + "}\n"
    + "pub fn at() {\n    // A comment.\n\n"
    + STATEMENT * 250
    + "}\n"
)
# 254 lines, a test function whose body has 251 code lines.
INTEGRATION = "#[test]\nfn long_test() {\n" + STATEMENT * 251 + "}\n"
# 10 lines.
GENERATED = (
    "// Generated by tools/packaging/generate_x.py --write. Do not edit.\n"
    + "pub const X: u8 = 1;\n" * 9
)
# 3 lines.
MAIN = "fn main() {\n    yamaa::run();\n}\n"


class SizeReport(unittest.TestCase):
    def setUp(self):
        directory = tempfile.TemporaryDirectory(prefix="yamaa-source-size-")
        self.addCleanup(directory.cleanup)
        self.root = Path(directory.name)

    def test_a_crate_row_counts_its_lines_by_kind_and_its_long_functions(self):
        for path, text in {
            "rust/crates/yamaa-core/src/lib.rs": LIB,
            "rust/crates/yamaa-core/src/checks.rs": CHECKS,
            "rust/crates/yamaa-core/src/long.rs": LONG,
            "rust/crates/yamaa-core/src/generated.rs": GENERATED,
            "rust/crates/yamaa-core/tests/main.rs": INTEGRATION,
            "rust/crates/yamaa-cli/src/main.rs": MAIN,
        }.items():
            write(self.root, path, text)
        # Core's source is lib.rs's 5 other lines and long.rs's 507; its tests
        # are lib.rs's 9 gated lines, checks.rs's 4 and tests/main.rs's 254;
        # over() and long_test() pass 250 lines, at() does not.
        self.assertEqual(
            run_main(source_size.main, "--root", str(self.root)),
            (
                0,
                "| Crate | Source | Test | Generated | Functions over 250 lines |\n"
                "| --- | ---: | ---: | ---: | ---: |\n"
                "| yamaa-cli | 3 | 0 | 0 | 0 |\n"
                "| yamaa-core | 512 | 267 | 10 | 2 |\n"
                "| Total | 515 | 267 | 10 | 2 |\n",
                "",
            ),
        )


if __name__ == "__main__":
    unittest.main()
