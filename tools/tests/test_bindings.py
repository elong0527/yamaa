"""Keep the generated Python binding declarations synchronized with the IDL."""

import copy
import tempfile
import unittest
from pathlib import Path
from unittest import mock

from tools.packaging import generate_bindings as generator


class BindingsTests(unittest.TestCase):
    def test_generated_outputs_match_shared_definition(self):
        rendered = generator.render_all()
        for target in generator.TARGETS:
            self.assertEqual(target.read_bytes(), rendered[target].encode("utf-8"))

    def test_rendering_is_deterministic(self):
        self.assertEqual(generator.render_all(), generator.render_all())

    def test_generated_outputs_carry_do_not_edit_header(self):
        for text in generator.render_all().values():
            self.assertIn("Generated by tools/packaging/generate_bindings.py", text)
            self.assertIn("Do not edit", text)

    def test_malformed_definition_shapes_raise_value_error(self):
        base = generator._load_definition()

        def mutated(mutate):
            definition = copy.deepcopy(base)
            mutate(definition)
            return definition

        def first_class(definition):
            return next(
                export
                for export in definition["python"]["exports"]
                if export["kind"] == "class"
            )

        def first_function(definition):
            return next(
                export
                for export in definition["python"]["exports"]
                if export["kind"] == "function"
            )

        cases = [
            (
                generator._validate_python,
                mutated(lambda d: d.update(python="x")),
            ),
            (
                generator._validate_python,
                mutated(lambda d: d["python"].pop("exports")),
            ),
            (
                generator._validate_python,
                mutated(lambda d: d["python"].update(exports="abc")),
            ),
            (
                generator._validate_python,
                mutated(lambda d: d["python"].update(exports=["abc"])),
            ),
            (
                generator._validate_python,
                mutated(lambda d: first_class(d).update(methods=["m"])),
            ),
            (
                generator._validate_python,
                mutated(lambda d: first_class(d).update(methods=[{}])),
            ),
            (
                generator._validate_python,
                mutated(lambda d: first_class(d).update(methods=[{"name": None}])),
            ),
            (
                generator._validate_python,
                mutated(lambda d: first_function(d).update(args={"bad-name": "text"})),
            ),
            (
                generator._validate_python,
                mutated(lambda d: first_function(d).update(args={"class": "text"})),
            ),
            (
                generator._validate_python,
                mutated(lambda d: d["python"].pop("issue_projection")),
            ),
            (
                generator._resolve_records_import,
                mutated(
                    lambda d: d["imports"]["records"].update(roles=[{"role": "x"}])
                ),
            ),
            (
                generator._resolve_records_import,
                mutated(lambda d: d.update(imports="x")),
            ),
            (
                generator._resolve_records_import,
                mutated(lambda d: d["imports"].update(records="x")),
            ),
            (
                generator._resolve_records_import,
                mutated(lambda d: d.update(handshake="x")),
            ),
            (
                generator._validate_operations,
                mutated(lambda d: d.pop("r")),
            ),
            (
                generator._validate_operations,
                mutated(lambda d: d["r"].pop("groups")),
            ),
            (
                generator._validate_operations,
                mutated(lambda d: d["r"].update(groups=[{}])),
            ),
            (
                generator._validate_operations,
                mutated(lambda d: d.update(operations="x")),
            ),
            (
                generator._validate_operations,
                mutated(lambda d: d.update(operations={"op": "x"})),
            ),
            (
                generator._validate_operations,
                mutated(lambda d: d.update(operations={"op": {"python": [123]}})),
            ),
        ]
        for validate, definition in cases:
            with self.subTest(validate=validate.__name__, definition=definition):
                with self.assertRaises(ValueError):
                    validate(definition)

    def test_non_mapping_top_level_raises_value_error(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "bindings.yaml"
            path.write_text("- just\n- a\n- list\n", encoding="utf-8")
            with mock.patch.object(generator, "DEFINITION", path):
                with self.assertRaises(ValueError):
                    generator._load_definition()

    def test_stub_wrap_keeps_short_definitions_on_one_line(self):
        self.assertEqual(
            generator._stub_def("f", "a: str", "str", ""),
            ["def f(a: str) -> str: ..."],
        )
        wrapped = generator._stub_def(
            "f", "a: str, " + "b: str, " * 20 + "c: str", "str", ""
        )
        self.assertGreater(len(wrapped), 1)
        self.assertTrue(all(len(line) <= 88 for line in wrapped[:-1]))


if __name__ == "__main__":
    unittest.main()
